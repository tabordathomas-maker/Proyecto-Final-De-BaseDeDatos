-- Description:	<SP CONSULTA VEHICULO POR ID>
-- =============================================
CREATE PROCEDURE SP_CONSULTA_VEHICULO
	@ID_VEHICULO INT
AS
BEGIN
	SET NOCOUNT ON;

	BEGIN TRY

		IF NOT EXISTS (SELECT 1 FROM VEHICULO WHERE ID_VEHICULO = @ID_VEHICULO)
			BEGIN
				RAISERROR('EL ID INGRESADO NO CORRESPONDE A UN VEHICULO',16,1)
				RETURN;
			END

		-- NECESITO VEHICULO - MODELO - MARCA
		SELECT V.ID_VEHICULO, V.PLACA,
			UPPER(MA.NOMBRE) AS MARCA, UPPER(MO.NOMBRE) AS MODELO,
			V.GAMA, V.CATEGORIA_LICENCIA, V.CAPACIDAD, V.PUERTAS,
			V.TRANSMISION, V.COMBUSTIBLE, V.CONSUMO, V.KILOMETRAJE, V.COLOR,
