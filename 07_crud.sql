PARÁMETROS :
  @CORREO               VARCHAR(100) CORREO PARA INGRESAR Y RECIBIR EL QR (ÚNICO)
  @ID_TIPO_DOCUMENTO    INT          1 = CÉDULA DE CIUDADANÍA, 2 = EXTRANJERÍA...
  @NUM_DOCUMENTO        VARCHAR(20)  NÚMERO DEL DOCUMENTO (ÚNICO CON EL TIPO)
  @NOMBRES              VARCHAR(45)  NOMBRE COMPLETO (OBLIGATORIO)
  @DIRECCION            VARCHAR(255) DIRECCIÓN
  @CODIGO_POSTAL        VARCHAR(10)  CÓDIGO POSTAL
