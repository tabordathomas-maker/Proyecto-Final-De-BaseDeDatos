			CASE
				WHEN V.ES_RESPALDO = 1 THEN 'STOCK DE RESPALDO (NO SE PUEDE RESERVAR)'
				ELSE 'SE PUEDE RESERVAR'
			END AS TIPO_STOCK
		FROM VEHICULO V   -- "V" es el alias de VEHICULO
		INNER JOIN MODELO MO ON MO.ID_MODELO = V.ID_MODELO   -- Se iguala PK con FK
		INNER JOIN MARCA MA ON MA.ID_MARCA = MO.ID_MARCA
		WHERE V.ID_VEHICULO = @ID_VEHICULO   -- EL "WHERE" ES PARA CONTROLAR

