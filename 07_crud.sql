/*
PROCEDIMIENTO 2 (R - READ):
CREAR UN PROCEDIMIENTO QUE PERMITA CONSULTAR UN CLIENTE POR SU ID, MOSTRANDO
SU CORREO, EL NOMBRE DEL TIPO DE DOCUMENTO, SU EDAD, SI SU LICENCIA ESTÁ VIGENTE,
LOS DÍAS QUE LE FALTAN PARA VENCER, QUÉ PUEDE HACER SEGÚN SU ESTADO Y SUS TELÉFONOS.

PROPÓSITO  : QUE EL COORDINADOR O EL CAJERO VEAN EN UNA SOLA LLAMADA TODO LO QUE
             NECESITAN DEL CLIENTE. NUNCA SE MUESTRA LA CONTRASEÑA (ÉTICA).
PARÁMETROS : @ID_CLIENTE INT  ID DEL CLIENTE (ES EL MISMO ID DEL USUARIO)
RETORNO    : 2 TABLAS: (1) LOS DATOS DEL CLIENTE (1 FILA) Y (2) SUS TELÉFONOS (2 FILAS).
EJEMPLO    : EXEC SP_CONSULTA_CLIENTE @ID_CLIENTE = 51

TABLAS     : CLIENTE - USUARIO - TIPO_DOCUMENTO - TELEFONO_CLIENTE - TIPO_TELEFONO
REGLA DEL CASO: ESTADOS DEL CLIENTE: AL DÍA, MOROSO (NO PUEDE RESERVAR) Y VETADO
                (NO PUEDE INGRESAR). EN LA ENTREGA SE VERIFICA LA LICENCIA VIGENTE.
*/

