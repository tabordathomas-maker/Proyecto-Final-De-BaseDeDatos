  @VENCIMIENTO_LICENCIA DATE         VENCIMIENTO (LA LICENCIA DEBE ESTAR VIGENTE)
  @ULTIMOS4_TARJETA     CHAR(4)      SOLO LOS ÚLTIMOS 4 DÍGITOS (ÉTICA)
  @TELEFONO_CELULAR     VARCHAR(20)  TELÉFONO 1, TIPO CELULAR (10 DÍGITOS)
  @TELEFONO_FIJO        VARCHAR(20)  TELÉFONO 2, TIPO FIJO (10 DÍGITOS)
RETORNO    : UNA FILA CON EL ID DEL CLIENTE NUEVO + MENSAJE 'CLIENTE INGRESADO
             CORRECTAMENTE'. SI HAY ERROR, UNA FILA CON LOS DATOS DEL ERROR.
EJEMPLO    : EXECUTE SP_INGRESO_CLIENTE @CORREO = 'laura.demo@correo.example', ... (VER DEMO 1)

REGLA DEL CASO: EL CLIENTE REGISTRA DOCUMENTO, NOMBRE, DIRECCIÓN CON CÓDIGO POSTAL,
                2 TELÉFONOS, CORREO, GÉNERO, FECHA DE NACIMIENTO, NIVEL DE ESTUDIOS
                Y LICENCIA CON SU FECHA DE VENCIMIENTO.
BENEFICIO     : NO QUEDAN USUARIOS "HUÉRFANOS" SIN CLIENTE, NI CLIENTES DUPLICADOS,
