-- =============================================
-- Author:		<THOMAS TABORDA Y COMPAÑERO(A)>
-- Create date: <10-11-2026>
-- Description:	<SP MODIFICAR CLIENTE - CLIENTE + USUARIO>
-- =============================================
CREATE PROCEDURE SP_MODIFICAR_CLIENTE
	@ID_CLIENTE INT,
	@CORREO VARCHAR(100),
	@NOMBRES VARCHAR(45),
	@DIRECCION VARCHAR(255),
	@CODIGO_POSTAL VARCHAR(10),
	@NIVEL_ESTUDIOS VARCHAR(45),
	@CATEGORIA_LICENCIA VARCHAR(45),
	@VENCIMIENTO_LICENCIA DATE,
	@ESTADO VARCHAR(45),
	@ULTIMOS4_TARJETA CHAR(4)
AS
BEGIN
	SET NOCOUNT ON;

	BEGIN TRY

		-- PASO 1: VALIDACIONES

		IF NOT EXISTS (SELECT 1 FROM CLIENTE WHERE ID_CLIENTE = @ID_CLIENTE)
			BEGIN
				RAISERROR('EL ID INGRESADO NO CORRESPONDE A UN CLIENTE',16,1)
				RETURN;
			END

		IF @NOMBRES IS NULL OR LTRIM(RTRIM(@NOMBRES)) = ''
			BEGIN
				RAISERROR('EL NOMBRE DEL CLIENTE ES OBLIGATORIO',16,1)
				RETURN;
			END

		-- EL CORREO NO PUEDE ESTAR USADO POR OTRO USUARIO (ID MENOR O MAYOR = "DISTINTO")
		IF EXISTS (SELECT 1 FROM USUARIO WHERE CORREO = @CORREO
					AND (ID_USUARIO < @ID_CLIENTE OR ID_USUARIO > @ID_CLIENTE))
			BEGIN
				RAISERROR('ESE CORREO YA LO TIENE OTRO USUARIO',16,1)
				RETURN;
			END

