/*
PROCEDIMIENTO 3 (U - UPDATE):
CREAR UN PROCEDIMIENTO QUE PERMITA MODIFICAR LOS DATOS DE UN CLIENTE: CORREO,
NOMBRE, DIRECCIÓN, CÓDIGO POSTAL, NIVEL DE ESTUDIOS, LICENCIA, ESTADO Y TARJETA.
SI EL CLIENTE QUEDA VETADO, SU USUARIO SE DESACTIVA (NO PUEDE INGRESAR).

PROPÓSITO  : ACTUALIZAR AL CLIENTE (POR EJEMPLO, CUANDO RENUEVA LA LICENCIA) Y
             CAMBIAR SU ESTADO (AL_DIA, MOROSO, VETADO).
PARÁMETROS :
  @ID_CLIENTE           INT          ID DEL CLIENTE A MODIFICAR
  @CORREO               VARCHAR(100) NUEVO CORREO (NO PUEDE SER DE OTRO USUARIO)
  @NOMBRES              VARCHAR(45)  NOMBRE COMPLETO (OBLIGATORIO)
  @DIRECCION            VARCHAR(255) DIRECCIÓN
  @CODIGO_POSTAL        VARCHAR(10)  CÓDIGO POSTAL
  @NIVEL_ESTUDIOS       VARCHAR(45)  NIVEL DE ESTUDIOS
  @CATEGORIA_LICENCIA   VARCHAR(45)  CATEGORÍA DE LA LICENCIA
  @VENCIMIENTO_LICENCIA DATE         NUEVO VENCIMIENTO DE LA LICENCIA
  @ESTADO               VARCHAR(45)  AL_DIA, MOROSO O VETADO
  @ULTIMOS4_TARJETA     CHAR(4)      ÚLTIMOS 4 DÍGITOS DE LA TARJETA
RETORNO    : MENSAJE 'CLIENTE MODIFICADO CON EXITO' O UNA FILA CON EL ERROR.
EJEMPLO    : EXECUTE SP_MODIFICAR_CLIENTE @ID_CLIENTE = 51, @CORREO = ..., @ESTADO = 'MOROSO', ...

NO SE MODIFICAN: EL DOCUMENTO NI LA FECHA DE NACIMIENTO (SON LA IDENTIDAD DE LA
                 PERSONA; SI ESTÁN MAL, SE CORRIGEN CON EL ADMINISTRADOR).
REGLA DEL CASO: VETADO = NO PUEDE INGRESAR AL SISTEMA.
BENEFICIO     : UN SOLO CAMBIO DE ESTADO BLOQUEA AL CLIENTE EN DOS TABLAS A LA VEZ.
