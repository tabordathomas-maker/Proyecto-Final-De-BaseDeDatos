-- =============================================
-- Author:		<THOMAS TABORDA Y COMPAÑERO(A)>
-- Create date: <10-11-2026>
-- Description:	<SP INGRESO CLIENTE - USUARIO + CLIENTE + TELEFONO_CLIENTE>
-- =============================================
CREATE PROCEDURE SP_INGRESO_CLIENTE
	@CORREO VARCHAR(100),
	@ID_TIPO_DOCUMENTO INT,
	@NUM_DOCUMENTO VARCHAR(20),
	@NOMBRES VARCHAR(45),
	@DIRECCION VARCHAR(255),
	@CODIGO_POSTAL VARCHAR(10),
	@GENERO VARCHAR(45),
	@FECHA_NACIMIENTO DATE,
	@NIVEL_ESTUDIOS VARCHAR(45),
	@NUM_LICENCIA VARCHAR(20),
	@CATEGORIA_LICENCIA VARCHAR(45),
	@VENCIMIENTO_LICENCIA DATE,
	@ULTIMOS4_TARJETA CHAR(4),
	@TELEFONO_CELULAR VARCHAR(20),
	@TELEFONO_FIJO VARCHAR(20)
AS
BEGIN
	SET NOCOUNT ON; -- no muestra el mensaje "(1 row affected)" de cada instrucción

	DECLARE @ID_USUARIO INT   -- AQUÍ SE GUARDA EL ID QUE GENERA EL IDENTITY DE USUARIO

	BEGIN TRY

		-- PASO 1: VALIDACIONES (NO SE TOCA NINGUNA TABLA HASTA QUE TODO ESTÉ BIEN)

		IF @NOMBRES IS NULL OR LTRIM(RTRIM(@NOMBRES)) = ''
			BEGIN
				RAISERROR('EL NOMBRE DEL CLIENTE ES OBLIGATORIO',16,1)
				RETURN;
			END

		IF EXISTS (SELECT 1 FROM USUARIO WHERE CORREO = @CORREO)   -- EL CORREO ES LLAVE CANDIDATA
			BEGIN
				RAISERROR('YA EXISTE UN USUARIO CON ESE CORREO',16,1)
				RETURN;
			END

		IF NOT EXISTS (SELECT 1 FROM TIPO_DOCUMENTO WHERE ID_TIPO_DOCUMENTO = @ID_TIPO_DOCUMENTO)
			BEGIN
				RAISERROR('EL TIPO DE DOCUMENTO NO EXISTE',16,1)
				RETURN;
			END

		IF EXISTS (SELECT 1 FROM CLIENTE WHERE ID_TIPO_DOCUMENTO = @ID_TIPO_DOCUMENTO
					AND NUM_DOCUMENTO = @NUM_DOCUMENTO)   -- TIPO + NÚMERO NO SE REPITEN
			BEGIN
				RAISERROR('YA EXISTE UN CLIENTE CON ESE DOCUMENTO',16,1)
				RETURN;
			END

		IF EXISTS (SELECT 1 FROM CLIENTE WHERE NUM_LICENCIA = @NUM_LICENCIA)
			BEGIN
				RAISERROR('YA EXISTE UN CLIENTE CON ESE NUMERO DE LICENCIA',16,1)
				RETURN;
			END

		IF DATEDIFF(YEAR, @FECHA_NACIMIENTO, GETDATE()) < 18   -- EDAD EN AÑOS HASTA HOY
			BEGIN
				RAISERROR('EL CLIENTE DEBE SER MAYOR DE EDAD',16,1)
				RETURN;
			END

		IF @VENCIMIENTO_LICENCIA < GETDATE()   -- EN LA ENTREGA SE EXIGE LICENCIA VIGENTE
			BEGIN
				RAISERROR('LA LICENCIA DE CONDUCCION ESTA VENCIDA',16,1)
				RETURN;
			END

		IF @TELEFONO_CELULAR = @TELEFONO_FIJO   -- EL CASO PIDE 2 TELÉFONOS DISTINTOS
			BEGIN
				RAISERROR('LOS DOS TELEFONOS DEBEN SER DIFERENTES',16,1)
				RETURN;
			END

		-- PASO 2: LA OPERACIÓN, DENTRO DE UNA TRANSACCIÓN (SE TOCAN 3 TABLAS)

		BEGIN TRANSACTION   -- DESDE AQUÍ: O SE GUARDA TODO, O NO SE GUARDA NADA

			-- 2.1 SUPERCLASE: USUARIO (CONTRASENA_HASH QUEDA EN NULL, VER DECISIÓN DEL 10 NOV)
			INSERT INTO USUARIO (CORREO, ROL, ACTIVO)
			VALUES (@CORREO, 'CLIENTE', 1)

			-- 2.2 SE BUSCA EL ID QUE LE DIO EL IDENTITY (EL CORREO ES ÚNICO)
			SELECT @ID_USUARIO = U.ID_USUARIO
			FROM USUARIO U   -- "U" es el alias de USUARIO
			WHERE U.CORREO = @CORREO

			-- 2.3 SUBCLASE: CLIENTE, CON EL MISMO ID DEL USUARIO (ESPECIALIZACIÓN)
			INSERT INTO CLIENTE (ID_CLIENTE, ID_TIPO_DOCUMENTO, NUM_DOCUMENTO, NOMBRES, DIRECCION,
				CODIGO_POSTAL, GENERO, FECHA_NACIMIENTO, NIVEL_ESTUDIOS, NUM_LICENCIA,
				CATEGORIA_LICENCIA, VENCIMIENTO_LICENCIA, ESTADO, ULTIMOS4_TARJETA)
			VALUES (@ID_USUARIO, @ID_TIPO_DOCUMENTO, @NUM_DOCUMENTO, UPPER(LTRIM(RTRIM(@NOMBRES))), @DIRECCION,
				@CODIGO_POSTAL, @GENERO, @FECHA_NACIMIENTO, @NIVEL_ESTUDIOS, @NUM_LICENCIA,
				@CATEGORIA_LICENCIA, @VENCIMIENTO_LICENCIA, 'AL_DIA', @ULTIMOS4_TARJETA)   -- TODO CLIENTE NUEVO EMPIEZA AL DÍA

			-- 2.4 LOS DOS TELÉFONOS (ATRIBUTO MULTIVALUADO). TIPO 1 = CELULAR, TIPO 2 = FIJO
			INSERT INTO TELEFONO_CLIENTE (ID_CLIENTE, ID_TIPO_TELEFONO, NUMERO)
			VALUES (@ID_USUARIO, 1, @TELEFONO_CELULAR),
				(@ID_USUARIO, 2, @TELEFONO_FIJO)

		COMMIT TRANSACTION   -- TODO SALIÓ BIEN: SE GUARDAN LAS 3 TABLAS

		-- PASO 3: MENSAJE DE ÉXITO
		SELECT @ID_USUARIO AS ID_CLIENTE_NUEVO, 'CLIENTE INGRESADO CORRECTAMENTE' AS MENSAJE
		PRINT 'CLIENTE INGRESADO CORRECTAMENTE'

	END TRY

	BEGIN CATCH
		IF @@TRANCOUNT > 0
			ROLLBACK TRANSACTION   -- SI ALGO FALLÓ, SE DESHACE TAMBIÉN EL USUARIO YA INSERTADO

		-- SE GUARDA EL ERROR EN LA TABLA DE CLASE (DESPUÉS DEL ROLLBACK, PARA QUE NO SE BORRE)
		INSERT INTO DB_Errors (UserName, ErrorNumber, ErrorState, ErrorSeverity, ErrorLine, ErrorProdure, ErrorMessage, ErrorDateTime)
		VALUES (SUSER_NAME(), ERROR_NUMBER(), ERROR_STATE(), ERROR_SEVERITY(), ERROR_LINE(), ERROR_PROCEDURE(), ERROR_MESSAGE(), GETDATE())

		SELECT ERROR_LINE() AS ERROR_LINEA,
				ERROR_MESSAGE() AS ERROR_MENSAJE,
				ERROR_NUMBER() AS ERROR_NUMERICO,
				ERROR_PROCEDURE() AS ERROR_DE_PROCEDIMIENTO,
				ERROR_SEVERITY() AS SEVERIDAD_DEL_ERROR,
				ERROR_STATE() AS ESTADO_DEL_ERROR,
				GETDATE() FECHA_ERROR,
				SUSER_NAME() AS USUARIO_SQL
	END CATCH
END
GO

