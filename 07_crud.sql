-- =============================================
-- Author:		<THOMAS TABORDA Y COMPAÑERO(A)>
-- Create date: <10-11-2026>
-- Description:	<SP CONSULTA CLIENTE POR ID>
-- =============================================
CREATE PROCEDURE SP_CONSULTA_CLIENTE
	@ID_CLIENTE INT
AS
BEGIN
	SET NOCOUNT ON;

	BEGIN TRY

		IF NOT EXISTS (SELECT 1 FROM CLIENTE WHERE ID_CLIENTE = @ID_CLIENTE)
			BEGIN
				RAISERROR('EL ID INGRESADO NO CORRESPONDE A UN CLIENTE',16,1)
				RETURN;
			END

		-- TABLA 1: DATOS DEL CLIENTE
		-- NECESITO CLIENTE - USUARIO - TIPO_DOCUMENTO
		SELECT C.ID_CLIENTE, C.NOMBRES, U.CORREO,
			TD.NOMBRE AS TIPO_DOCUMENTO, C.NUM_DOCUMENTO,
			C.DIRECCION, C.CODIGO_POSTAL, C.GENERO,
			C.FECHA_NACIMIENTO, DATEDIFF(YEAR, C.FECHA_NACIMIENTO, GETDATE()) AS EDAD,
			C.NIVEL_ESTUDIOS, C.NUM_LICENCIA, C.CATEGORIA_LICENCIA, C.VENCIMIENTO_LICENCIA,
			CASE
				WHEN C.VENCIMIENTO_LICENCIA >= GETDATE() THEN 'VIGENTE'
				ELSE 'VENCIDA'
			END AS LICENCIA,
			DATEDIFF(DAY, GETDATE(), C.VENCIMIENTO_LICENCIA) AS DIAS_PARA_VENCER_LICENCIA,
			C.ESTADO,
			CASE C.ESTADO
				WHEN 'AL_DIA' THEN 'PUEDE RESERVAR'
				WHEN 'MOROSO' THEN 'NO PUEDE RESERVAR'
				WHEN 'VETADO' THEN 'NO PUEDE INGRESAR'
			END AS PERMISO,
			C.ULTIMOS4_TARJETA   -- SOLO 4 DÍGITOS; LA CONTRASEÑA NO SE MUESTRA
		FROM CLIENTE C   -- "C" es el alias de CLIENTE
		INNER JOIN USUARIO U ON U.ID_USUARIO = C.ID_CLIENTE   -- Se iguala PK con FK (ESPECIALIZACIÓN)
		INNER JOIN TIPO_DOCUMENTO TD ON TD.ID_TIPO_DOCUMENTO = C.ID_TIPO_DOCUMENTO
		WHERE C.ID_CLIENTE = @ID_CLIENTE   -- EL "WHERE" ES PARA CONTROLAR

		-- TABLA 2: SUS TELÉFONOS
		-- NECESITO TELEFONO_CLIENTE - TIPO_TELEFONO
		SELECT TC.NUMERO, TT.NOMBRE AS TIPO_TELEFONO
		FROM TELEFONO_CLIENTE TC   -- "TC" es el alias de TELEFONO_CLIENTE
		INNER JOIN TIPO_TELEFONO TT ON TT.ID_TIPO_TELEFONO = TC.ID_TIPO_TELEFONO
		WHERE TC.ID_CLIENTE = @ID_CLIENTE

		PRINT 'LOS DATOS DEL CLIENTE A MOSTRAR SON LOS SIGUIENTES'

	END TRY

	BEGIN CATCH
		IF @@TRANCOUNT > 0
			ROLLBACK TRANSACTION

		INSERT INTO DB_Errors (UserName, ErrorNumber, ErrorState, ErrorSeverity, ErrorLine, ErrorProdure, ErrorMessage, ErrorDateTime)
		VALUES (SUSER_NAME(), ERROR_NUMBER(), ERROR_STATE(), ERROR_SEVERITY(), ERROR_LINE(), ERROR_PROCEDURE(), ERROR_MESSAGE(), GETDATE())

		SELECT ERROR_LINE() AS ERROR_LINEA,
				ERROR_MESSAGE() AS ERROR_MENSAJE,
				ERROR_NUMBER() AS ERROR_NUMERICO,
				ERROR_PROCEDURE() AS ERROR_DE_PROCEDIMIENTO,
				ERROR_SEVERITY() AS SEVERIDAD_DEL_ERROR,
				ERROR_STATE() AS ESTADO_DEL_ERROR,
				GETDATE() FECHA_ERROR,
				SUSER_NAME() AS USUARIO_SQL
	END CATCH
END
GO

