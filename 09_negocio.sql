PARÁMETROS     : @ID_MODALIDAD INT, @GAMA VARCHAR(45), @KILOMETRAJE INT (ODÓMETRO EN LA ENTREGA)
RETORNO        : DECIMAL(14,2). VALOR DEL DÍA (NULL SI NO HAY TARIFA PARA ESOS DATOS)
