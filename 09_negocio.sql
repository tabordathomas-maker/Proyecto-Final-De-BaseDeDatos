-- Create date: <10-11-2026>
-- Description:	<FUNCIÓN ESCALAR - VALOR DÍA DE LA TARIFA>
-- =============================================
CREATE FUNCTION FN_VALOR_DIA_TARIFA
(
@ID_MODALIDAD INT,
@GAMA VARCHAR(45),
@KILOMETRAJE INT
)
RETURNS DECIMAL(14,2)
AS
BEGIN

	DECLARE @VALOR_DIA DECIMAL(14,2)

	SELECT @VALOR_DIA = T.VALOR_DIA
	FROM TARIFA T  -- "T" es el alias de TARIFA
	WHERE T.ID_MODALIDAD = @ID_MODALIDAD
	AND T.GAMA = @GAMA
	AND T.KM_MIN <= @KILOMETRAJE
	AND (T.KM_MAX >= @KILOMETRAJE OR T.KM_MAX IS NULL)  -- EL ÚLTIMO RANGO NO TIENE TOPE

	RETURN @VALOR_DIA

END
GO

