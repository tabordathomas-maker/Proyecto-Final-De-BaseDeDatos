		SELECT A.ID_ALQUILER, R.CODIGO_RESERVA, C.NOMBRES AS CLIENTE, V.PLACA,
		       A.FECHA_ENTREGA, A.FECHA_FIN_PACTADA, @DIAS AS DIAS_PACTADOS,
		       @VALOR_DIA AS TARIFA_DIA, @VALOR_POLIZA AS POLIZA_DIA,
		       @VALOR_ALQUILER AS VALOR_ALQUILER, @DESCUENTO AS DESCUENTO_CONVENIO,
		       A.ANTICIPO AS ANTICIPO_A_COBRAR
		FROM ALQUILER A
		INNER JOIN RESERVA R ON R.ID_RESERVA = A.ID_RESERVA
