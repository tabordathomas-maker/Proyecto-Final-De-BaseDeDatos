/*
PROCEDIMIENTO 1 (NECESIDAD 1):
CREAR UN PROCEDIMIENTO QUE REGISTRE LA ENTREGA DEL VEHÍCULO DE UNA RESERVA: VERIFICA AL
CLIENTE Y AL COORDINADOR, CALCULA EL ANTICIPO (30 % DEL ALQUILER CON DESCUENTO), CREA EL
ALQUILER Y EL ACTA DE ENTREGA, Y ANOTA COMO "PREVIOS" LOS DAÑOS QUE EL CARRO YA TRAÍA.

PROPÓSITO  : AUTOMATIZAR LA ENTREGA, SIN ENTREGAR CARROS A CLIENTES QUE NO CUMPLEN.
PARÁMETROS : @ID_RESERVA       INT       RESERVA CONFIRMADA O MODIFICADA
             @ID_EMPLEADO      INT       COORDINADOR ACTIVO QUE HACE EL ACTA
             @FECHA_ENTREGA    DATETIME  FECHA Y HORA DE LA ENTREGA ('AAAA-MM-DDTHH:MM:SS')
             @KILOMETRAJE      INT       ODÓMETRO EN LA ENTREGA
             @NIVEL_GASOLINA   TINYINT   0 A 100 (NORMALMENTE 100)
             @DIAS_AMPLIACION  INT       DÍAS QUE EL CLIENTE AMPLÍA EN LA ENTREGA (POR DEFECTO 0)
RETORNO    : UNA FILA CON EL ALQUILER CREADO Y SU ANTICIPO. SI FALLA: LA FILA DEL ERROR
             (Y QUEDA EN DB_Errors). NO DEJA NADA A MEDIAS.
USA        : FN_VALIDAR_CLIENTE, FN_VALOR_DIA_TARIFA, FN_DIAS_COBRAR, FN_DESCUENTO_CONVENIO,
             FN_DANIOS_ULTIMA_DEVOLUCION (CURSOR)
DISPARA    : TRG_ENTREGA_ALQUILER -> TRG_AUDITORIA_VEHICULO
EJEMPLO    : EXEC SP_REGISTRAR_ENTREGA @ID_RESERVA = 60, @ID_EMPLEADO = 6,
             @FECHA_ENTREGA = '2026-11-14T10:00:00', @KILOMETRAJE = 42361,
             @NIVEL_GASOLINA = 100, @DIAS_AMPLIACION = 0
             -> 3 DÍAS X (105.600 + 45.000) = 451.800; ANTICIPO 30 % = 135.540
*/

-- =============================================
-- Author:		<THOMAS>
-- Create date: <10-11-2026>
-- Description:	<SP DE NEGOCIO 1 - REGISTRAR ENTREGA DEL VEHÍCULO>
-- =============================================
CREATE PROCEDURE SP_REGISTRAR_ENTREGA
	@ID_RESERVA INT,
	@ID_EMPLEADO INT,
	@FECHA_ENTREGA DATETIME,
	@KILOMETRAJE INT,
	@NIVEL_GASOLINA TINYINT,
	@DIAS_AMPLIACION INT = 0
AS
BEGIN
	SET NOCOUNT ON; -- inicializa las varibles

	DECLARE @ID_VEHICULO INT
	DECLARE @KM_VEHICULO INT
	DECLARE @ESTADO_VEHICULO VARCHAR(45)
	DECLARE @ID_MODALIDAD INT
	DECLARE @GAMA VARCHAR(45)
	DECLARE @FECHA_FIN DATETIME
	DECLARE @FIN_PACTADA DATETIME
	DECLARE @VALOR_POLIZA DECIMAL(14,2)
	DECLARE @VALOR_DIA DECIMAL(14,2)
	DECLARE @DIAS INT
	DECLARE @VALOR_ALQUILER DECIMAL(14,2)
	DECLARE @DESCUENTO DECIMAL(14,2)
	DECLARE @ANTICIPO DECIMAL(14,2)
	DECLARE @MENSAJE VARCHAR(100)
	DECLARE @ID_ALQUILER INT
	DECLARE @ID_INSPECCION INT
	DECLARE @DESCRIPCION_PREVIA VARCHAR(255)  -- VARIABLE DONDE EL CURSOR DEJA CADA FILA

	BEGIN TRY

		-- -------- VALIDACIONES (SI ALGUNA FALLA, EL RAISERROR SALTA AL CATCH) --------

		IF NOT EXISTS (SELECT 1 FROM RESERVA WHERE ID_RESERVA = @ID_RESERVA
		               AND ESTADO IN ('CONFIRMADA', 'MODIFICADA'))
		BEGIN
			RAISERROR('LA RESERVA NO EXISTE O NO ESTA CONFIRMADA (YA SE CUMPLIO O SE CANCELO)', 16, 1)
			RETURN;
		END

		IF NOT EXISTS (SELECT 1 FROM EMPLEADO E
		               INNER JOIN USUARIO U ON U.ID_USUARIO = E.ID_EMPLEADO
		               WHERE E.ID_EMPLEADO = @ID_EMPLEADO
		               AND E.CARGO = 'COORDINADOR' AND U.ACTIVO = 1)
		BEGIN
			RAISERROR('EL EMPLEADO NO ES UN COORDINADOR ACTIVO: NO PUEDE HACER EL ACTA DE ENTREGA', 16, 1)
			RETURN;
		END

		IF @DIAS_AMPLIACION < 0
		BEGIN
			RAISERROR('LOS DIAS DE AMPLIACION NO PUEDEN SER NEGATIVOS', 16, 1)
			RETURN;
		END

		-- -------- DATOS DE LA RESERVA --------
		-- NECESITO RESERVA - VEHICULO - POLIZA
		SELECT @ID_VEHICULO = R.ID_VEHICULO,
		       @KM_VEHICULO = V.KILOMETRAJE,
		       @ESTADO_VEHICULO = V.ESTADO,
		       @ID_MODALIDAD = R.ID_MODALIDAD,
		       @GAMA = V.GAMA,
		       @FECHA_FIN = R.FECHA_FIN,
		       @VALOR_POLIZA = P.VALOR_DIA
		FROM RESERVA R
		INNER JOIN VEHICULO V ON V.ID_VEHICULO = R.ID_VEHICULO
		INNER JOIN POLIZA P ON P.ID_POLIZA = R.ID_POLIZA
		WHERE R.ID_RESERVA = @ID_RESERVA

		IF @ESTADO_VEHICULO IN ('EN_MANTENIMIENTO', 'FUERA_DE_SERVICIO', 'ALQUILADO')
		BEGIN
			RAISERROR('EL VEHICULO NO ESTA EN CONDICIONES DE ENTREGARSE (TALLER, FUERA DE SERVICIO O YA ALQUILADO)', 16, 1)
			RETURN;
		END

		IF @KILOMETRAJE < @KM_VEHICULO
		BEGIN
			RAISERROR('EL KILOMETRAJE NO PUEDE SER MENOR AL ODOMETRO REGISTRADO DEL VEHICULO', 16, 1)
			RETURN;
		END

		SET @FIN_PACTADA = DATEADD(DAY, @DIAS_AMPLIACION, @FECHA_FIN)  -- AMPLIACIÓN DEL TIEMPO EN LA ENTREGA

		IF @FECHA_ENTREGA >= @FIN_PACTADA
		BEGIN
			RAISERROR('LA FECHA DE ENTREGA DEBE SER ANTERIOR AL FIN DEL ALQUILER', 16, 1)
			RETURN;
		END

		-- VALIDACIÓN CON FUNCIÓN: MOROSO, VETADO, LICENCIA VENCIDA O CATEGORÍA
		SET @MENSAJE = DBO.FN_VALIDAR_CLIENTE(@ID_RESERVA, @FIN_PACTADA)
		IF @MENSAJE IN ('APTO')
			PRINT 'CLIENTE VERIFICADO: ' + @MENSAJE
		ELSE
		BEGIN
			RAISERROR(@MENSAJE, 16, 1)
			RETURN;
		END

		-- -------- CÁLCULOS CON FUNCIONES --------
		SET @VALOR_DIA = DBO.FN_VALOR_DIA_TARIFA(@ID_MODALIDAD, @GAMA, @KILOMETRAJE)
		SET @DIAS = DBO.FN_DIAS_COBRAR(@FECHA_ENTREGA, @FIN_PACTADA)
		SET @VALOR_ALQUILER = @DIAS * (@VALOR_DIA + @VALOR_POLIZA)  -- DÍAS X (TARIFA + PÓLIZA)
		SET @DESCUENTO = DBO.FN_DESCUENTO_CONVENIO(@ID_RESERVA, @VALOR_ALQUILER)
		SET @ANTICIPO = (@VALOR_ALQUILER + @DESCUENTO) * 30 / 100  -- ANTICIPO = 30 %

		-- -------- TRANSACCIÓN: DESDE AQUÍ, O SE GUARDA TODO O NO SE GUARDA NADA --------
		BEGIN TRANSACTION

			-- PASO A: CREAR EL ALQUILER (DISPARA TRG_ENTREGA_ALQUILER)
			INSERT INTO ALQUILER (ID_RESERVA, FECHA_ENTREGA, FECHA_FIN_PACTADA, ANTICIPO)
			VALUES (@ID_RESERVA, @FECHA_ENTREGA, @FIN_PACTADA, @ANTICIPO)

			SELECT @ID_ALQUILER = A.ID_ALQUILER
			FROM ALQUILER A
			WHERE A.ID_RESERVA = @ID_RESERVA  -- UNA RESERVA = UN ALQUILER (UQ_ALQUILER_RESERVA)

			-- PASO B: ACTA DE ENTREGA (TIPO 1)
			INSERT INTO INSPECCION (ID_ALQUILER, ID_EMPLEADO, ID_TIPO_INSPECCION, FECHA_HORA, KILOMETRAJE, NIVEL_GASOLINA)
			VALUES (@ID_ALQUILER, @ID_EMPLEADO, 1, @FECHA_ENTREGA, @KILOMETRAJE, @NIVEL_GASOLINA)

			SELECT @ID_INSPECCION = I.ID_INSPECCION
			FROM INSPECCION I
			WHERE I.ID_ALQUILER = @ID_ALQUILER AND I.ID_TIPO_INSPECCION = 1

			-- PASO C: CURSOR -> ANOTAR CADA DAÑO QUE EL CARRO YA TRAÍA, CON VALOR 0 (NO SE COBRA)

			-- FASE 1: DECLARE (LOCAL = SOLO EXISTE DENTRO DE ESTE PROCEDIMIENTO)
			DECLARE CUR_DANIOS_PREVIOS CURSOR LOCAL FOR
				SELECT DP.DESCRIPCION
				FROM DBO.FN_DANIOS_ULTIMA_DEVOLUCION(@ID_VEHICULO) DP  -- LA FUNCIÓN DE TABLA ALIMENTA EL CURSOR

			-- FASE 2: OPEN
			OPEN CUR_DANIOS_PREVIOS

			-- FASE 3: FETCH (LEE LA PRIMERA FILA; @@FETCH_STATUS = 0 SIGNIFICA QUE SÍ HABÍA FILA)
			FETCH NEXT FROM CUR_DANIOS_PREVIOS INTO @DESCRIPCION_PREVIA

			WHILE @@FETCH_STATUS = 0
			BEGIN
				INSERT INTO DANIO (ID_INSPECCION, DESCRIPCION, VALOR)
				VALUES (@ID_INSPECCION, 'Previo: ' + @DESCRIPCION_PREVIA, 0)

