PARÁMETROS     : @ID_RESERVA INT, @VALOR_ALQUILER DECIMAL(14,2)
RETORNO        : DECIMAL(14,2). EL DESCUENTO EN NEGATIVO (ASÍ VA EN LA FACTURA). 0 SI NO HAY CONVENIO
EJEMPLO        : PRINT DBO.FN_DESCUENTO_CONVENIO(3, 2028500)  -> -141995.00 (CONVENIO DEL 7 %)
