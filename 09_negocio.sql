CREATE FUNCTION FN_DANIOS_A_COBRAR
(
@ID_ALQUILER INT
)
RETURNS TABLE
AS
RETURN
(
	-- NECESITO ALQUILER - RESERVA - POLIZA - INSPECCION - DANIO
	SELECT TOP(50) D.ID_DANO, D.DESCRIPCION, D.VALOR
	FROM ALQUILER A  -- "A" es el alias de ALQUILER
	INNER JOIN RESERVA R ON R.ID_RESERVA = A.ID_RESERVA  -- Se iguala PK con FK
	INNER JOIN POLIZA P ON P.ID_POLIZA = R.ID_POLIZA
	INNER JOIN INSPECCION I ON I.ID_ALQUILER = A.ID_ALQUILER
	INNER JOIN DANIO D ON D.ID_INSPECCION = I.ID_INSPECCION
	WHERE A.ID_ALQUILER = @ID_ALQUILER
	AND I.ID_TIPO_INSPECCION = 2              -- SOLO LOS DE LA DEVOLUCIÓN
	AND D.VALOR > 0
	AND P.NOMBRE IN ('BASICA', 'INTERMEDIA')  -- PREMIUM = CUBRIMIENTO TOTAL, NO SE COBRA
	ORDER BY D.ID_DANO
