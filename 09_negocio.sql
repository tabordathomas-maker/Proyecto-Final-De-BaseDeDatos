/*
TRIGGER 1: TRG_ENTREGA_ALQUILER  (TABLA ALQUILER, FOR INSERT)
CUANDO NACE UN ALQUILER:
 - SI EL CLIENTE ESTÁ MOROSO O VETADO, LO RECHAZA (RAISERROR + ROLLBACK TRAN), AUNQUE
   ALGUIEN HAGA EL INSERT DIRECTO SIN USAR EL PROCEDIMIENTO.
 - SI TODO ESTÁ BIEN: LA RESERVA PASA A 'CUMPLIDA' Y EL VEHÍCULO A 'ALQUILADO'.
REGLA DEL CASO : "MOROSO NO PUEDE RESERVAR"; "LA RESERVA SE VUELVE ALQUILER EN LA ENTREGA".
BENEFICIO      : EL CATÁLOGO DEJA DE MOSTRAR EL CARRO SIN QUE NADIE TENGA QUE ACORDARSE.
*/

IF EXISTS (SELECT * FROM sys.triggers WHERE name = 'TRG_ENTREGA_ALQUILER')
	DROP TRIGGER TRG_ENTREGA_ALQUILER
GO

CREATE TRIGGER TRG_ENTREGA_ALQUILER
ON ALQUILER
	FOR INSERT
AS
BEGIN
	SET NOCOUNT ON;

	-- REGLA 1: CLIENTE MOROSO O VETADO -> NO SE ENTREGA
	IF EXISTS (SELECT 1 FROM inserted I
	           INNER JOIN RESERVA R ON R.ID_RESERVA = I.ID_RESERVA
	           INNER JOIN CLIENTE C ON C.ID_CLIENTE = R.ID_CLIENTE
	           WHERE C.ESTADO IN ('MOROSO', 'VETADO'))
	BEGIN
		RAISERROR('TRIGGER: EL CLIENTE ESTA MOROSO O VETADO. NO SE LE PUEDE ENTREGAR EL VEHICULO', 16, 1)
		ROLLBACK TRANSACTION  -- SE DESHACE EL INSERT
		RETURN;
	END

	-- REGLA 2: LA RESERVA QUEDA CUMPLIDA
	UPDATE RESERVA
	SET ESTADO = 'CUMPLIDA'
	WHERE ID_RESERVA IN (SELECT ID_RESERVA FROM inserted)

	-- REGLA 3: EL VEHÍCULO QUEDA ALQUILADO (ESTE UPDATE DISPARA TRG_AUDITORIA_VEHICULO)
	UPDATE VEHICULO
	SET ESTADO = 'ALQUILADO'
	WHERE ID_VEHICULO IN (SELECT R.ID_VEHICULO FROM inserted I
	                      INNER JOIN RESERVA R ON R.ID_RESERVA = I.ID_RESERVA)

	PRINT 'TRIGGER: SE ACTUALIZO LA RESERVA (CUMPLIDA) Y EL VEHICULO (ALQUILADO) CON EXITO'
END
GO

