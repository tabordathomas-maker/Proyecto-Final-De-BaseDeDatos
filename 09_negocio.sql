FUNCIÓN 3:
DESARROLLAR UNA FUNCIÓN ESCALAR QUE VERIFIQUE SI AL CLIENTE DE UNA RESERVA SE LE PUEDE
ENTREGAR EL VEHÍCULO: QUE NO ESTÉ MOROSO NI VETADO, QUE LA LICENCIA NO SE VENZA ANTES DE
TERMINAR EL ALQUILER Y QUE LA CATEGORÍA DE LA LICENCIA SIRVA PARA EL VEHÍCULO.

REGLA DEL CASO : "MOROSO NO PUEDE RESERVAR, VETADO NO PUEDE INGRESAR" Y "EL COORDINADOR
                 VERIFICA QUE LA LICENCIA ESTÉ VIGENTE Y SEA DE LA CATEGORÍA CORRECTA".
PARÁMETROS     : @ID_RESERVA INT, @FIN_PACTADA DATETIME (FIN DEL ALQUILER, CON LA AMPLIACIÓN)
RETORNO        : VARCHAR(100). 'APTO' O EL MOTIVO POR EL QUE NO SE ENTREGA
EJEMPLO        : SELECT DBO.FN_VALIDAR_CLIENTE(60, '2026-11-17T10:00:00')  -> 'APTO'
*/

-- =============================================
-- Author:		<THOMAS>
-- Create date: <10-11-2026>
-- Description:	<FUNCIÓN ESCALAR - VALIDAR CLIENTE PARA LA ENTREGA>
-- =============================================
CREATE FUNCTION FN_VALIDAR_CLIENTE
(
@ID_RESERVA INT,
@FIN_PACTADA DATETIME
)
RETURNS VARCHAR(100)
AS
BEGIN

	DECLARE @MENSAJE VARCHAR(100)
	DECLARE @ESTADO VARCHAR(45)
	DECLARE @VENCE_LICENCIA DATE
	DECLARE @LICENCIA_CLIENTE VARCHAR(45)
	DECLARE @LICENCIA_VEHICULO VARCHAR(45)

	-- NECESITO RESERVA - CLIENTE - VEHICULO
	SELECT @ESTADO = C.ESTADO,
	       @VENCE_LICENCIA = C.VENCIMIENTO_LICENCIA,
	       @LICENCIA_CLIENTE = C.CATEGORIA_LICENCIA,
	       @LICENCIA_VEHICULO = V.CATEGORIA_LICENCIA
	FROM RESERVA R  -- "R" es el alias de RESERVA
	INNER JOIN CLIENTE C ON C.ID_CLIENTE = R.ID_CLIENTE  -- Se iguala PK con FK
	INNER JOIN VEHICULO V ON V.ID_VEHICULO = R.ID_VEHICULO
	WHERE R.ID_RESERVA = @ID_RESERVA

	SET @MENSAJE = 'APTO'

	IF @ESTADO IN ('MOROSO', 'VETADO')
		SET @MENSAJE = 'EL CLIENTE ESTA ' + @ESTADO + ': NO SE LE PUEDE ENTREGAR EL VEHICULO'
	ELSE
		IF DATEDIFF(DAY, @FIN_PACTADA, @VENCE_LICENCIA) < 0  -- LA LICENCIA VENCE ANTES DEL FIN
		SET @MENSAJE = 'LA LICENCIA DEL CLIENTE VENCE ANTES DE TERMINAR EL ALQUILER'
			ELSE
				IF (@LICENCIA_VEHICULO = 'B1' AND @LICENCIA_CLIENTE IN ('A1', 'A2'))
				OR (@LICENCIA_VEHICULO = 'B2' AND @LICENCIA_CLIENTE IN ('A1', 'A2', 'B1', 'C1'))
				SET @MENSAJE = 'LA CATEGORIA DE LA LICENCIA NO SIRVE PARA ESTE VEHICULO'

	RETURN @MENSAJE

END
GO

