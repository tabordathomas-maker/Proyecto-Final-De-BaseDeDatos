PARÁMETROS     : @NIVEL_GASOLINA INT (0 A 100, EL NIVEL EN LA DEVOLUCIÓN)
RETORNO        : DECIMAL(14,2). RECARGO (0 SI EL TANQUE ESTÁ LLENO)
EJEMPLO        : PRINT DBO.FN_RECARGO_COMBUSTIBLE(40)  -> 60 X 2200 = 132000.00 (IGUAL A LA FACTURA 1)
*/

-- =============================================
-- Author:		<THOMAS>
-- Create date: <10-11-2026>
-- Description:	<FUNCIÓN ESCALAR - RECARGO POR GASOLINA>
-- =============================================
CREATE FUNCTION FN_RECARGO_COMBUSTIBLE
(
@NIVEL_GASOLINA INT
)
RETURNS DECIMAL(14,2)
AS
BEGIN

	DECLARE @RECARGO DECIMAL(14,2)

	IF @NIVEL_GASOLINA < 100
		SET @RECARGO = (100 - @NIVEL_GASOLINA) * 2200  -- LO QUE FALTA PARA LLENAR X 2.200 COP
	ELSE
		SET @RECARGO = 0  -- TANQUE LLENO

	RETURN @RECARGO

END
GO

PRINT DBO.FN_RECARGO_COMBUSTIBLE(40)   -- RESULTADO 132000.00
PRINT DBO.FN_RECARGO_COMBUSTIBLE(100)  -- RESULTADO 0.00
GO

