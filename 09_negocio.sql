CREATE TRIGGER TRG_TOTAL_FACTURA
ON DETALLE_FACTURA
	FOR INSERT, UPDATE, DELETE
AS
BEGIN
	SET NOCOUNT ON;

	-- 1) TOTAL DE LA FACTURA = SUMA DEL DETALLE (inserted = LÍNEAS NUEVAS, deleted = LÍNEAS BORRADAS)
	UPDATE FACTURA
	SET TOTAL = (SELECT SUM(DF.VALOR) FROM DETALLE_FACTURA DF
	             WHERE DF.ID_FACTURA = FACTURA.ID_FACTURA)
	WHERE ID_FACTURA IN (SELECT ID_FACTURA FROM inserted
	                     UNION
	                     SELECT ID_FACTURA FROM deleted)

	-- 2) VALOR TOTAL DEL ALQUILER = TOTAL DE SU FACTURA
	UPDATE ALQUILER
	SET VALOR_TOTAL = (SELECT F.TOTAL FROM FACTURA F
	                   WHERE F.ID_ALQUILER = ALQUILER.ID_ALQUILER)
	WHERE ID_ALQUILER IN (SELECT F.ID_ALQUILER FROM FACTURA F
	                      WHERE F.ID_FACTURA IN (SELECT ID_FACTURA FROM inserted
	                                             UNION
	                                             SELECT ID_FACTURA FROM deleted))
END
GO

