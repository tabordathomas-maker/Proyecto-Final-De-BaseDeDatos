REGLA DEL CASO : EL ACTA DE ENTREGA REGISTRA EL ESTADO DEL VEHÍCULO.
BENEFICIO      : AL NUEVO CLIENTE NO SE LE COBRA UN DAÑO QUE YA TRAÍA EL CARRO.
PARÁMETROS     : @ID_VEHICULO INT
RETORNO        : TABLA (ID_DANO, DESCRIPCION, VALOR). LA USA EL CURSOR DE SP_REGISTRAR_ENTREGA
EJEMPLO        : SELECT * FROM DBO.FN_DANIOS_ULTIMA_DEVOLUCION(22)  -> 2 REGISTROS
*/

-- =============================================
-- Author:		<THOMAS>
-- Create date: <10-11-2026>
-- Description:	<FUNCIÓN DE TABLA - DAÑOS DE LA ÚLTIMA DEVOLUCIÓN DE UN VEHÍCULO>
-- =============================================
CREATE FUNCTION FN_DANIOS_ULTIMA_DEVOLUCION
(
@ID_VEHICULO INT
)
RETURNS TABLE
AS
RETURN
(
	SELECT TOP(50) D.ID_DANO, D.DESCRIPCION, D.VALOR
	FROM DANIO D  -- "D" es el alias de DANIO
	WHERE D.VALOR > 0  -- LOS DE VALOR 0 YA ERAN "PREVIOS"
	AND D.ID_INSPECCION IN (SELECT TOP(1) I.ID_INSPECCION     -- LA ÚLTIMA ACTA DE DEVOLUCIÓN
	                        FROM INSPECCION I
	                        INNER JOIN ALQUILER A ON A.ID_ALQUILER = I.ID_ALQUILER
	                        INNER JOIN RESERVA R ON R.ID_RESERVA = A.ID_RESERVA
	                        WHERE R.ID_VEHICULO = @ID_VEHICULO
	                        AND I.ID_TIPO_INSPECCION = 2  -- 2 = DEVOLUCIÓN
	                        ORDER BY I.FECHA_HORA DESC)
	ORDER BY D.ID_DANO
)
GO

