/*
FUNCIÓN 6:
DESARROLLAR UNA FUNCIÓN ESCALAR QUE CALCULE EL RECARGO POR EXCESO DE KILOMETRAJE.
SOLO APLICA EN LA MODALIDAD POR DÍA (200 KM POR DÍA). CADA KM DE MÁS VALE TARIFA / 200.

REGLA DEL CASO : "MODALIDAD POR DÍA CON RESTRICCIÓN DE KILOMETRAJE: SE COBRA EL EXCESO".
PARÁMETROS     : @ID_MODALIDAD INT, @VALOR_DIA DECIMAL(14,2), @DIAS INT, @KM_RECORRIDOS INT
RETORNO        : DECIMAL(14,2). RECARGO (0 EN LA MODALIDAD POR KILOMETRAJE O SI NO SE PASÓ)
EJEMPLO        : PRINT DBO.FN_RECARGO_EXCESO_KM(2, 169200, 10, 2314)
                 -> 2314 - 2000 = 314 KM X 846 = 265644.00 (IGUAL A LA FACTURA 5)
*/

-- =============================================
-- Author:		<THOMAS>
-- Create date: <10-11-2026>
-- Description:	<FUNCIÓN ESCALAR - RECARGO POR EXCESO DE KM>
-- =============================================
CREATE FUNCTION FN_RECARGO_EXCESO_KM
(
@ID_MODALIDAD INT,
@VALOR_DIA DECIMAL(14,2),
@DIAS INT,
@KM_RECORRIDOS INT
)
RETURNS DECIMAL(14,2)
AS
BEGIN

	DECLARE @LIMITE_DIA INT
	DECLARE @KM_EXCESO INT
	DECLARE @RECARGO DECIMAL(14,2)

	SELECT @LIMITE_DIA = M.KM_LIMITE_DIA
	FROM MODALIDAD M  -- "M" es el alias de MODALIDAD
	WHERE M.ID_MODALIDAD = @ID_MODALIDAD

	SET @RECARGO = 0

	IF @LIMITE_DIA > 0  -- POR_KILOMETRAJE TIENE LÍMITE NULL: NO ENTRA AQUÍ Y EL RECARGO QUEDA EN 0
	BEGIN
		SET @KM_EXCESO = @KM_RECORRIDOS - (@LIMITE_DIA * @DIAS)  -- KM DE MÁS
		IF @KM_EXCESO > 0
			SET @RECARGO = @KM_EXCESO * (@VALOR_DIA / @LIMITE_DIA)  -- CADA KM EXTRA = TARIFA / 200
	END

	RETURN @RECARGO

END
GO

PRINT DBO.FN_RECARGO_EXCESO_KM(2, 169200, 10, 2314)  -- RESULTADO 265644.00
PRINT DBO.FN_RECARGO_EXCESO_KM(1, 169200, 10, 9000)  -- RESULTADO 0.00 (POR KILOMETRAJE, SIN LÍMITE)
GO

