-- =============================================
-- Author:		<THOMAS>
-- Create date: <10-11-2026>
-- Description:	<FUNCIÓN ESCALAR - DESCUENTO POR CONVENIO>
-- =============================================
CREATE FUNCTION FN_DESCUENTO_CONVENIO
(
@ID_RESERVA INT,
@VALOR_ALQUILER DECIMAL(14,2)
)
RETURNS DECIMAL(14,2)
AS
BEGIN

	DECLARE @PORCENTAJE DECIMAL(5,2)
	DECLARE @DESCUENTO DECIMAL(14,2)

	SELECT @PORCENTAJE = CV.PORCENTAJE_DESCUENTO
	FROM RESERVA R
	INNER JOIN CONVENIO CV ON CV.ID_CONVENIO = R.ID_CONVENIO  -- "CV" es el alias de CONVENIO
	WHERE R.ID_RESERVA = @ID_RESERVA

	IF @PORCENTAJE IS NULL
		SET @DESCUENTO = 0  -- LA RESERVA NO TIENE CONVENIO
	ELSE
		SET @DESCUENTO = -1 * @VALOR_ALQUILER * @PORCENTAJE / 100  -- NEGATIVO: SE RESTA EN LA FACTURA

	RETURN @DESCUENTO

END
GO

