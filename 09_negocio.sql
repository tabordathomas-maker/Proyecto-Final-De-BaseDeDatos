-- Description:	<FUNCIÓN ESCALAR - RECARGO POR RETRASO>
-- =============================================
CREATE FUNCTION FN_RECARGO_RETRASO
(
@VALOR_DIA DECIMAL(14,2),
@FIN_PACTADA DATETIME,
@DEVOLUCION DATETIME
)
RETURNS DECIMAL(14,2)
AS
BEGIN

	DECLARE @DIAS_RETRASO INT
	DECLARE @RECARGO DECIMAL(14,2)

	SET @DIAS_RETRASO = DBO.FN_DIAS_COBRAR(@FIN_PACTADA, @DEVOLUCION)  -- UNA FUNCIÓN USA A OTRA

	IF @DIAS_RETRASO = 0
		SET @RECARGO = 0  -- LO DEVOLVIÓ A TIEMPO
	ELSE
		SET @RECARGO = @VALOR_DIA + (@DIAS_RETRASO - 1) * 2 * @VALOR_DIA  -- PRIMER DÍA SENCILLO, LOS DEMÁS DOBLES

	RETURN @RECARGO

END
GO

