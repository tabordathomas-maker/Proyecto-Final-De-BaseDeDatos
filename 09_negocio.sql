/*
FUNCIÓN 1:
DESARROLLAR UNA FUNCIÓN ESCALAR QUE CALCULE CUÁNTOS DÍAS SE COBRAN ENTRE DOS FECHAS.
UN DÍA EMPEZADO SE COBRA COMPLETO (25 HORAS = 2 DÍAS).

REGLA DEL CASO : EL ALQUILER Y EL RETRASO SE COBRAN POR DÍAS.
PARÁMETROS     : @DESDE DATETIME, @HASTA DATETIME
RETORNO        : INT. NÚMERO DE DÍAS (0 SI @HASTA NO ES POSTERIOR A @DESDE)
EJEMPLO        : PRINT DBO.FN_DIAS_COBRAR('2026-11-14T10:00:00', '2026-11-17T10:00:00')  -> 3
*/

-- =============================================
-- Author:		<THOMAS>
-- Create date: <10-11-2026>
-- Description:	<FUNCIÓN ESCALAR - DÍAS A COBRAR ENTRE DOS FECHAS>
-- =============================================
CREATE FUNCTION FN_DIAS_COBRAR
(
@DESDE DATETIME,
@HASTA DATETIME
)
RETURNS INT
AS
BEGIN

	DECLARE @HORAS INT
	DECLARE @DIAS INT

	SET @HORAS = DATEDIFF(HOUR, @DESDE, @HASTA)  -- HORAS ENTRE LAS DOS FECHAS

	IF @HORAS <= 0
		SET @DIAS = 0  -- NO HAY DÍAS QUE COBRAR (EJ: DEVOLVIÓ ANTES DE TIEMPO)
	ELSE
		SET @DIAS = (@HORAS + 23) / 24  -- DIVISIÓN ENTERA QUE REDONDEA HACIA ARRIBA (25 H -> 2 DÍAS)

	RETURN @DIAS

END
GO

PRINT DBO.FN_DIAS_COBRAR('2026-11-14T10:00:00', '2026-11-17T10:00:00')  -- RESULTADO 3
PRINT DBO.FN_DIAS_COBRAR('2026-11-17T10:00:00', '2026-11-18T15:00:00')  -- 29 HORAS -> RESULTADO 2
