/*
TRIGGER 2: TRG_DEVOLUCION_VEHICULO  (TABLA INSPECCION, FOR INSERT)
CUANDO SE GUARDA UN ACTA DE DEVOLUCIÓN (ID_TIPO_INSPECCION = 2):
 - SI EL KILOMETRAJE ES MENOR QUE EL DE LA ENTREGA, LO RECHAZA (EL ODÓMETRO NO RETROCEDE).
   UN CHECK NO PUEDE HACER ESTO: NECESITA COMPARAR DOS FILAS (ENTREGA Y DEVOLUCIÓN).
 - SI ESTÁ BIEN: EL VEHÍCULO TOMA EL NUEVO KILOMETRAJE Y QUEDA 'DISPONIBLE'
   (O 'RESERVADO' SI YA TIENE OTRA RESERVA CONFIRMADA).
REGLA DEL CASO : "EN LA DEVOLUCIÓN SE REGISTRA EL KILOMETRAJE"; CATÁLOGO DE DISPONIBLES.
BENEFICIO      : EL KILOMETRAJE DEL CARRO (BASE DE LA TARIFA) SIEMPRE ESTÁ AL DÍA.
*/

IF EXISTS (SELECT * FROM sys.triggers WHERE name = 'TRG_DEVOLUCION_VEHICULO')
	DROP TRIGGER TRG_DEVOLUCION_VEHICULO
GO

CREATE TRIGGER TRG_DEVOLUCION_VEHICULO
ON INSPECCION
	FOR INSERT
AS
BEGIN
	SET NOCOUNT ON;

	-- REGLA 1: EL KM DE LA DEVOLUCIÓN NO PUEDE SER MENOR AL DE LA ENTREGA
	IF EXISTS (SELECT 1 FROM inserted I
	           INNER JOIN INSPECCION EN ON EN.ID_ALQUILER = I.ID_ALQUILER  -- "EN" = ACTA DE ENTREGA
	           WHERE I.ID_TIPO_INSPECCION = 2
	           AND EN.ID_TIPO_INSPECCION = 1
	           AND I.KILOMETRAJE < EN.KILOMETRAJE)
	BEGIN
		RAISERROR('TRIGGER: EL KILOMETRAJE DE LA DEVOLUCION NO PUEDE SER MENOR AL DE LA ENTREGA', 16, 1)
		ROLLBACK TRANSACTION
		RETURN;
	END

	-- REGLA 2: SOLO PARA ACTAS DE DEVOLUCIÓN, ACTUALIZAR EL VEHÍCULO
	IF EXISTS (SELECT 1 FROM inserted WHERE ID_TIPO_INSPECCION = 2)
	BEGIN
		UPDATE VEHICULO
		SET KILOMETRAJE = (SELECT I.KILOMETRAJE FROM inserted I
		                   INNER JOIN ALQUILER A ON A.ID_ALQUILER = I.ID_ALQUILER
		                   INNER JOIN RESERVA R ON R.ID_RESERVA = A.ID_RESERVA
		                   WHERE R.ID_VEHICULO = VEHICULO.ID_VEHICULO
		                   AND I.ID_TIPO_INSPECCION = 2),
		    ESTADO = CASE
		             WHEN EXISTS (SELECT 1 FROM RESERVA R2
		                          WHERE R2.ID_VEHICULO = VEHICULO.ID_VEHICULO
		                          AND R2.ESTADO IN ('CONFIRMADA', 'MODIFICADA')) THEN 'RESERVADO'
		             ELSE 'DISPONIBLE'
		             END
		WHERE ID_VEHICULO IN (SELECT R.ID_VEHICULO FROM inserted I
		                      INNER JOIN ALQUILER A ON A.ID_ALQUILER = I.ID_ALQUILER
		                      INNER JOIN RESERVA R ON R.ID_RESERVA = A.ID_RESERVA
		                      WHERE I.ID_TIPO_INSPECCION = 2)

		PRINT 'TRIGGER: SE ACTUALIZO EL VEHICULO (NUEVO KILOMETRAJE Y ESTADO) CON EXITO'
	END
END
GO

