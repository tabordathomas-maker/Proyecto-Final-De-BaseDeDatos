/*
PROCEDIMIENTO 2 (NECESIDAD 2):
CREAR UN PROCEDIMIENTO QUE REGISTRE LA DEVOLUCIÓN DEL VEHÍCULO: CIERRA EL ALQUILER, HACE
EL ACTA DE DEVOLUCIÓN, REGISTRA EL DAÑO (SI LO HAY), CREA LA FACTURA Y LE AGREGA UNA LÍNEA
POR CADA COBRO: ALQUILER, RETRASO, EXCESO DE KM, GASOLINA, CADA DAÑO Y EL DESCUENTO.

PROPÓSITO  : QUE LA FACTURA SE CALCULE SOLA Y SIN ERRORES CON LAS REGLAS DEL CASO.
PARÁMETROS : @ID_ALQUILER        INT            ALQUILER ENTREGADO Y SIN DEVOLVER
             @ID_EMPLEADO        INT            COORDINADOR ACTIVO QUE HACE EL ACTA
             @FECHA_DEVOLUCION   DATETIME       FECHA Y HORA EN QUE LLEGA EL CARRO
             @KILOMETRAJE        INT            ODÓMETRO EN LA DEVOLUCIÓN
             @NIVEL_GASOLINA     TINYINT        0 A 100
             @CODIGO_FACTURA     VARCHAR(20)    CONSECUTIVO DE FACTURACIÓN (EJ: 'FV-2026-00051')
             @DESCRIPCION_DANIO  VARCHAR(255)   DAÑO ENCONTRADO (OPCIONAL, NULL SI NO HAY)
             @VALOR_DANIO        DECIMAL(14,2)  VALORACIÓN DEL DAÑO (OPCIONAL, 0 SI NO HAY)
RETORNO    : LAS LÍNEAS DE LA FACTURA CON SU TOTAL. SI FALLA: LA FILA DEL ERROR (Y DB_Errors).
USA        : FN_VALOR_DIA_TARIFA, FN_DIAS_COBRAR, FN_DESCUENTO_CONVENIO, FN_RECARGO_RETRASO,
             FN_RECARGO_EXCESO_KM, FN_RECARGO_COMBUSTIBLE, FN_DANIOS_A_COBRAR (CURSOR)
DISPARA    : TRG_DEVOLUCION_VEHICULO -> TRG_AUDITORIA_VEHICULO, Y TRG_TOTAL_FACTURA (CADA LÍNEA)
EJEMPLO    : (DESPUÉS DE LA ENTREGA DE LA RESERVA 60)
             EXEC SP_REGISTRAR_DEVOLUCION @ID_ALQUILER = <EL NUEVO>, @ID_EMPLEADO = 7,
             @FECHA_DEVOLUCION = '2026-11-18T15:00:00', @KILOMETRAJE = 43100,
             @NIVEL_GASOLINA = 70, @CODIGO_FACTURA = 'FV-2026-00051',
             @DESCRIPCION_DANIO = 'Rayon en puerta trasera izquierda', @VALOR_DANIO = 350000
             -> TOTAL 1.257.992 (VER DEMO 1)
*/

-- =============================================
-- Author:		<THOMAS>
-- Create date: <10-11-2026>
-- Description:	<SP DE NEGOCIO 2 - REGISTRAR DEVOLUCIÓN Y FACTURA>
-- =============================================
CREATE PROCEDURE SP_REGISTRAR_DEVOLUCION
	@ID_ALQUILER INT,
	@ID_EMPLEADO INT,
	@FECHA_DEVOLUCION DATETIME,
	@KILOMETRAJE INT,
	@NIVEL_GASOLINA TINYINT,
	@CODIGO_FACTURA VARCHAR(20),
	@DESCRIPCION_DANIO VARCHAR(255) = NULL,
	@VALOR_DANIO DECIMAL(14,2) = 0
AS
BEGIN
	SET NOCOUNT ON;

	DECLARE @ID_RESERVA INT
	DECLARE @ID_MODALIDAD INT
	DECLARE @GAMA VARCHAR(45)
	DECLARE @FECHA_ENTREGA DATETIME
	DECLARE @FIN_PACTADA DATETIME
	DECLARE @VALOR_POLIZA DECIMAL(14,2)
	DECLARE @KM_ENTREGA INT
	DECLARE @VALOR_DIA DECIMAL(14,2)
	DECLARE @DIAS INT
	DECLARE @VALOR_ALQUILER DECIMAL(14,2)
	DECLARE @DESCUENTO DECIMAL(14,2)
	DECLARE @RECARGO_RETRASO DECIMAL(14,2)
	DECLARE @RECARGO_KM DECIMAL(14,2)
	DECLARE @RECARGO_GASOLINA DECIMAL(14,2)
	DECLARE @ID_INSPECCION INT
	DECLARE @ID_FACTURA INT
	DECLARE @LINEA INT
	DECLARE @DESCRIPCION_CURSOR VARCHAR(255)   -- VARIABLES DONDE EL CURSOR DEJA CADA FILA
	DECLARE @VALOR_CURSOR DECIMAL(14,2)

	BEGIN TRY

		-- -------- VALIDACIONES --------

		IF NOT EXISTS (SELECT 1 FROM ALQUILER WHERE ID_ALQUILER = @ID_ALQUILER
		               AND FECHA_DEVOLUCION IS NULL)
		BEGIN
			RAISERROR('EL ALQUILER NO EXISTE O YA FUE DEVUELTO', 16, 1)
			RETURN;
		END

		IF NOT EXISTS (SELECT 1 FROM EMPLEADO E
		               INNER JOIN USUARIO U ON U.ID_USUARIO = E.ID_EMPLEADO
		               WHERE E.ID_EMPLEADO = @ID_EMPLEADO
		               AND E.CARGO = 'COORDINADOR' AND U.ACTIVO = 1)
		BEGIN
			RAISERROR('EL EMPLEADO NO ES UN COORDINADOR ACTIVO: NO PUEDE HACER EL ACTA DE DEVOLUCION', 16, 1)
			RETURN;
		END

		IF EXISTS (SELECT 1 FROM FACTURA WHERE CODIGO = @CODIGO_FACTURA)
		BEGIN
			RAISERROR('EL CODIGO DE FACTURA YA EXISTE', 16, 1)
			RETURN;
		END

		IF @VALOR_DANIO < 0 OR (@VALOR_DANIO > 0 AND @DESCRIPCION_DANIO IS NULL)
		BEGIN
			RAISERROR('EL DANIO DEBE TENER DESCRIPCION Y UN VALOR MAYOR O IGUAL A CERO', 16, 1)
			RETURN;
		END

		-- -------- DATOS DEL ALQUILER --------
		-- NECESITO ALQUILER - RESERVA - VEHICULO - POLIZA - INSPECCION (ACTA DE ENTREGA)
		SELECT @ID_RESERVA = A.ID_RESERVA,
		       @FECHA_ENTREGA = A.FECHA_ENTREGA,
		       @FIN_PACTADA = A.FECHA_FIN_PACTADA,
		       @ID_MODALIDAD = R.ID_MODALIDAD,
		       @GAMA = V.GAMA,
		       @VALOR_POLIZA = P.VALOR_DIA,
		       @KM_ENTREGA = I.KILOMETRAJE
		FROM ALQUILER A
		INNER JOIN RESERVA R ON R.ID_RESERVA = A.ID_RESERVA
		INNER JOIN VEHICULO V ON V.ID_VEHICULO = R.ID_VEHICULO
		INNER JOIN POLIZA P ON P.ID_POLIZA = R.ID_POLIZA
		INNER JOIN INSPECCION I ON I.ID_ALQUILER = A.ID_ALQUILER
		WHERE A.ID_ALQUILER = @ID_ALQUILER
		AND I.ID_TIPO_INSPECCION = 1  -- 1 = ENTREGA

		IF @KM_ENTREGA IS NULL
		BEGIN
			RAISERROR('EL ALQUILER NO TIENE ACTA DE ENTREGA', 16, 1)
			RETURN;
		END

		-- -------- CÁLCULOS CON FUNCIONES (UNA POR CADA REGLA DE COBRO) --------
		SET @VALOR_DIA = DBO.FN_VALOR_DIA_TARIFA(@ID_MODALIDAD, @GAMA, @KM_ENTREGA)  -- TARIFA CON EL KM DE LA ENTREGA
		SET @DIAS = DBO.FN_DIAS_COBRAR(@FECHA_ENTREGA, @FIN_PACTADA)
		SET @VALOR_ALQUILER = @DIAS * (@VALOR_DIA + @VALOR_POLIZA)
		SET @DESCUENTO = DBO.FN_DESCUENTO_CONVENIO(@ID_RESERVA, @VALOR_ALQUILER)
		SET @RECARGO_RETRASO = DBO.FN_RECARGO_RETRASO(@VALOR_DIA, @FIN_PACTADA, @FECHA_DEVOLUCION)
		SET @RECARGO_KM = DBO.FN_RECARGO_EXCESO_KM(@ID_MODALIDAD, @VALOR_DIA, @DIAS, @KILOMETRAJE - @KM_ENTREGA)
		SET @RECARGO_GASOLINA = DBO.FN_RECARGO_COMBUSTIBLE(@NIVEL_GASOLINA)

		-- -------- TRANSACCIÓN: O SE GUARDA TODO O NO SE GUARDA NADA --------
		BEGIN TRANSACTION

			-- PASO A: CERRAR EL ALQUILER
			UPDATE ALQUILER
			SET FECHA_DEVOLUCION = @FECHA_DEVOLUCION
			WHERE ID_ALQUILER = @ID_ALQUILER

			-- PASO B: ACTA DE DEVOLUCIÓN (TIPO 2) -> DISPARA TRG_DEVOLUCION_VEHICULO
			INSERT INTO INSPECCION (ID_ALQUILER, ID_EMPLEADO, ID_TIPO_INSPECCION, FECHA_HORA, KILOMETRAJE, NIVEL_GASOLINA)
			VALUES (@ID_ALQUILER, @ID_EMPLEADO, 2, @FECHA_DEVOLUCION, @KILOMETRAJE, @NIVEL_GASOLINA)

			SELECT @ID_INSPECCION = I.ID_INSPECCION
			FROM INSPECCION I
			WHERE I.ID_ALQUILER = @ID_ALQUILER AND I.ID_TIPO_INSPECCION = 2

			-- PASO C: DAÑO ENCONTRADO EN LA INSPECCIÓN
			IF @VALOR_DANIO > 0
				INSERT INTO DANIO (ID_INSPECCION, DESCRIPCION, VALOR)
				VALUES (@ID_INSPECCION, @DESCRIPCION_DANIO, @VALOR_DANIO)

			-- PASO D: FACTURA (EL TOTAL ARRANCA EN 0 Y LO LLENA EL TRIGGER)
			INSERT INTO FACTURA (ID_ALQUILER, CODIGO, FECHA, TOTAL)
			VALUES (@ID_ALQUILER, @CODIGO_FACTURA, @FECHA_DEVOLUCION, 0)

			SELECT @ID_FACTURA = F.ID_FACTURA
			FROM FACTURA F
			WHERE F.ID_ALQUILER = @ID_ALQUILER  -- UN ALQUILER = UNA FACTURA (UQ_FACTURA_ALQUILER)

			-- PASO E: LÍNEAS DE LA FACTURA (CADA INSERT DISPARA TRG_TOTAL_FACTURA)
			-- LA LÍNEA ALQUILER VA PRIMERO: ASÍ EL TOTAL NUNCA QUEDA MENOR QUE EL ANTICIPO (CK_ALQUILER_VALORES)
			SET @LINEA = 1
			INSERT INTO DETALLE_FACTURA (ID_FACTURA, LINEA, CONCEPTO, VALOR)
			VALUES (@ID_FACTURA, @LINEA, 'ALQUILER', @VALOR_ALQUILER)

			IF @RECARGO_RETRASO > 0
			BEGIN
				SET @LINEA = @LINEA + 1
				INSERT INTO DETALLE_FACTURA (ID_FACTURA, LINEA, CONCEPTO, VALOR)
				VALUES (@ID_FACTURA, @LINEA, 'RETRASO', @RECARGO_RETRASO)
			END

			IF @RECARGO_KM > 0
			BEGIN
				SET @LINEA = @LINEA + 1
				INSERT INTO DETALLE_FACTURA (ID_FACTURA, LINEA, CONCEPTO, VALOR)
				VALUES (@ID_FACTURA, @LINEA, 'EXCESO_KM', @RECARGO_KM)
			END

			IF @RECARGO_GASOLINA > 0
			BEGIN
				SET @LINEA = @LINEA + 1
				INSERT INTO DETALLE_FACTURA (ID_FACTURA, LINEA, CONCEPTO, VALOR)
				VALUES (@ID_FACTURA, @LINEA, 'COMBUSTIBLE', @RECARGO_GASOLINA)
			END

			-- PASO F: CURSOR -> UNA LÍNEA DE FACTURA POR CADA DAÑO QUE SE COBRA

			-- FASE 1: DECLARE
			DECLARE CUR_DANIOS_COBRAR CURSOR LOCAL FOR
				SELECT DC.DESCRIPCION, DC.VALOR
				FROM DBO.FN_DANIOS_A_COBRAR(@ID_ALQUILER) DC  -- SI LA PÓLIZA ES PREMIUM, NO TRAE FILAS

			-- FASE 2: OPEN
			OPEN CUR_DANIOS_COBRAR

			-- FASE 3: FETCH
			FETCH NEXT FROM CUR_DANIOS_COBRAR INTO @DESCRIPCION_CURSOR, @VALOR_CURSOR

			WHILE @@FETCH_STATUS = 0
			BEGIN
				SET @LINEA = @LINEA + 1  -- EL CURSOR PERMITE NUMERAR LAS LÍNEAS UNA POR UNA
				INSERT INTO DETALLE_FACTURA (ID_FACTURA, LINEA, CONCEPTO, VALOR)
				VALUES (@ID_FACTURA, @LINEA, 'DANIO', @VALOR_CURSOR)

				PRINT 'DANIO COBRADO EN LA FACTURA: ' + @DESCRIPCION_CURSOR

				FETCH NEXT FROM CUR_DANIOS_COBRAR INTO @DESCRIPCION_CURSOR, @VALOR_CURSOR
			END

			-- FASE 4: CLOSE
			CLOSE CUR_DANIOS_COBRAR

			-- FASE 5: DEALLOCATE
			DEALLOCATE CUR_DANIOS_COBRAR

			-- PASO G: DESCUENTO DEL CONVENIO (ÚLTIMA LÍNEA, NEGATIVA, SOLO SOBRE EL ALQUILER)
			IF @DESCUENTO < 0
			BEGIN
				SET @LINEA = @LINEA + 1
				INSERT INTO DETALLE_FACTURA (ID_FACTURA, LINEA, CONCEPTO, VALOR)
				VALUES (@ID_FACTURA, @LINEA, 'DESCUENTO_CONVENIO', @DESCUENTO)
			END

		COMMIT TRANSACTION  -- TODO SALIÓ BIEN: SE GUARDA

		PRINT 'DEVOLUCION Y FACTURA REGISTRADAS CORRECTAMENTE'

		-- RESULTADO PARA EL CAJERO: LA FACTURA CON SUS LÍNEAS
		SELECT F.CODIGO, F.FECHA, DF.LINEA, DF.CONCEPTO, DF.VALOR,
		       F.TOTAL AS TOTAL_FACTURA, A.ANTICIPO, A.VALOR_TOTAL AS VALOR_TOTAL_ALQUILER
		FROM FACTURA F
		INNER JOIN DETALLE_FACTURA DF ON DF.ID_FACTURA = F.ID_FACTURA
		INNER JOIN ALQUILER A ON A.ID_ALQUILER = F.ID_ALQUILER
		WHERE F.ID_FACTURA = @ID_FACTURA
		ORDER BY DF.LINEA

	END TRY

	BEGIN CATCH
		IF @@TRANCOUNT > 0
			ROLLBACK TRANSACTION  -- ATOMICIDAD: NI ALQUILER CERRADO, NI ACTA, NI FACTURA A MEDIAS

		INSERT INTO DB_Errors (UserName, ErrorNumber, ErrorState, ErrorSeverity, ErrorLine, ErrorProdure, ErrorMessage, ErrorDateTime)
		VALUES (SUSER_NAME(), ERROR_NUMBER(), ERROR_STATE(), ERROR_SEVERITY(), ERROR_LINE(), ERROR_PROCEDURE(), ERROR_MESSAGE(), GETDATE())

		SELECT ERROR_LINE() AS ERROR_LINEA,
				ERROR_MESSAGE() AS ERROR_MENSAJE,
				ERROR_NUMBER() AS ERROR_NUMERICO,
				ERROR_PROCEDURE() AS ERROR_DE_PROCEDIMIENTO,
				ERROR_SEVERITY() AS SEVERIDAD_DEL_ERROR,
				ERROR_STATE() AS ESTADO_DEL_ERROR,
				GETDATE() FECHA_ERROR,
				SUSER_NAME() AS USUARIO_SQL
	END CATCH
END
