-- =====================================================================
-- CONSULTA 1: INNER JOIN
-- =====================================================================

/*
CONSULTA 1 (INNER JOIN):
LISTAR LOS VEHÍCULOS ALQUILADOS POR CADA CLIENTE, CON EL NOMBRE DEL CLIENTE
EN MAYÚSCULAS, LA PLACA, LA MARCA, EL MODELO Y LA GAMA DEL VEHÍCULO, LA SEDE
DONDE LO RECOGIÓ, LA FECHA DE ENTREGA, EL MES, LA FECHA DE DEVOLUCIÓN,
LOS DÍAS QUE LO TUVO Y EL VALOR TOTAL PAGADO,
ORDENADO POR CLIENTE Y POR FECHA DE ENTREGA

REGLA DEL CASO : CONSULTA PEDIDA "VEHÍCULOS ALQUILADOS POR CLIENTE".
BENEFICIO      : EL GERENTE VE QUÉ ALQUILA CADA CLIENTE Y CUÁNTO PAGA
                 (CLIENTES FRECUENTES, CANDIDATOS A CONVENIO).
POR QUÉ INNER  : SOLO INTERESAN LAS RESERVAS QUE SÍ SE VOLVIERON ALQUILER;
                 LAS CANCELADAS O FUTURAS NO TIENEN PAREJA EN ALQUILER Y SE
                 QUEDAN POR FUERA.
TABLAS (7)     : CLIENTE - RESERVA - ALQUILER - VEHICULO - MODELO - MARCA - SEDE
RESULTADO ESPERADO: 50 REGISTROS (UNO POR ALQUILER)
*/

-- NECESITO CLIENTE - RESERVA - ALQUILER - VEHICULO - MODELO - MARCA - SEDE

SELECT UPPER(C.NOMBRES) AS NOMBRE_CLIENTE, V.PLACA, MA.NOMBRE AS MARCA,
MO.NOMBRE AS MODELO, V.GAMA, S.NOMBRE AS SEDE_RECOGIDA,
A.FECHA_ENTREGA, UPPER(DATENAME(MONTH, A.FECHA_ENTREGA)) AS MES_ENTREGA,
A.FECHA_DEVOLUCION,
DATEDIFF(DAY, A.FECHA_ENTREGA, A.FECHA_DEVOLUCION) AS DIAS_ALQUILADO,
A.VALOR_TOTAL AS VALOR_PAGADO

FROM CLIENTE C  -- "C" es el alias de CLIENTE
INNER JOIN RESERVA R ON C.ID_CLIENTE = R.ID_CLIENTE  -- Se iguala PK con FK
INNER JOIN ALQUILER A ON R.ID_RESERVA = A.ID_RESERVA  -- SOLO RESERVAS QUE SE VOLVIERON ALQUILER
INNER JOIN VEHICULO V ON V.ID_VEHICULO = R.ID_VEHICULO
INNER JOIN MODELO MO ON MO.ID_MODELO = V.ID_MODELO
INNER JOIN MARCA MA ON MA.ID_MARCA = MO.ID_MARCA
INNER JOIN SEDE S ON S.ID_SEDE = R.ID_SEDE

ORDER BY NOMBRE_CLIENTE, A.FECHA_ENTREGA  -- TOTAL REGISTROS 50
GO


---   -----          ------          -----


-- =====================================================================
-- CONSULTA 2: LEFT JOIN
-- =====================================================================

/*
CONSULTA 2 (LEFT JOIN):
LISTAR TODA LA FLOTA DE VEHÍCULOS CON SU PLACA, MARCA, MODELO, GAMA, SI ES
DEL STOCK DE RESPALDO Y SU ESTADO, JUNTO CON EL HISTORIAL DE SUS RESERVAS
(CÓDIGO, ESTADO, FECHA DE ENTREGA Y DE DEVOLUCIÓN) Y LA CALIFICACIÓN DE LA
ENCUESTA DE SATISFACCIÓN (SERVICIO Y VEHÍCULO). LOS VEHÍCULOS QUE NUNCA SE
HAN RESERVADO TAMBIÉN DEBEN APARECER,
ORDENADO POR MARCA, PLACA Y FECHA DE INICIO DE LA RESERVA

REGLA DEL CASO : CONSULTA PEDIDA "HISTORIAL DEL VEHÍCULO: FECHAS Y SATISFACCIÓN"
                 Y "DISPONIBLES".
BENEFICIO      : EL GERENTE VE QUÉ CARROS SE MUEVEN Y CUÁLES NO (NULL = NUNCA
                 RESERVADO), PARA PROMOCIONARLOS O SACARLOS DE LA FLOTA.
POR QUÉ LEFT   : SE QUIEREN TODOS LOS VEHÍCULOS (TABLA DE LA IZQUIERDA), AUNQUE
                 NO TENGAN RESERVA, ALQUILER O ENCUESTA.
TABLAS (6)     : VEHICULO - MODELO - MARCA - RESERVA - ALQUILER - ENCUESTA
RESULTADO ESPERADO: 96 REGISTROS = 66 RESERVAS + 30 VEHÍCULOS SIN RESERVA
*/

-- NECESITO VEHICULO - MODELO - MARCA - RESERVA - ALQUILER - ENCUESTA

SELECT V.PLACA, MA.NOMBRE AS MARCA, MO.NOMBRE AS MODELO, V.GAMA,
CASE V.ES_RESPALDO
	WHEN 1 THEN 'SI'
	ELSE 'NO'
END AS ES_RESPALDO,
V.ESTADO AS ESTADO_VEHICULO,
R.CODIGO_RESERVA, R.ESTADO AS ESTADO_RESERVA,
A.FECHA_ENTREGA, A.FECHA_DEVOLUCION,
E.CALIF_SERVICIO, E.CALIF_VEHICULO

FROM VEHICULO V  -- "V" es el alias de VEHICULO (LA TABLA DE LA IZQUIERDA)
INNER JOIN MODELO MO ON MO.ID_MODELO = V.ID_MODELO  -- TODO VEHÍCULO TIENE MODELO
INNER JOIN MARCA MA ON MA.ID_MARCA = MO.ID_MARCA  -- TODO MODELO TIENE MARCA
LEFT JOIN RESERVA R ON V.ID_VEHICULO = R.ID_VEHICULO  -- SI NO TIENE RESERVA SALE NULL
LEFT JOIN ALQUILER A ON R.ID_RESERVA = A.ID_RESERVA  -- RESERVA CANCELADA O FUTURA -> NULL
LEFT JOIN ENCUESTA E ON A.ID_ALQUILER = E.ID_ALQUILER

ORDER BY MA.NOMBRE, V.PLACA, R.FECHA_INICIO  -- TOTAL REGISTROS 96
GO

---- ---------

/*
CONSULTA 2B (PARA LA EXPOSICIÓN):
LA MISMA CONSULTA, PERO SOLO LOS VEHÍCULOS QUE NUNCA SE HAN RESERVADO
(LOS QUE EN LA CONSULTA 2 SALEN CON NULL EN LA RESERVA)
RESULTADO ESPERADO: 30 REGISTROS (6 SON DEL STOCK DE RESPALDO, QUE POR REGLA
DEL CASO NO SE PUEDE RESERVAR)
*/

SELECT V.PLACA, MA.NOMBRE AS MARCA, MO.NOMBRE AS MODELO, V.GAMA,
CASE V.ES_RESPALDO
	WHEN 1 THEN 'SI'
	ELSE 'NO'
END AS ES_RESPALDO,
V.ESTADO AS ESTADO_VEHICULO

FROM VEHICULO V
INNER JOIN MODELO MO ON MO.ID_MODELO = V.ID_MODELO
INNER JOIN MARCA MA ON MA.ID_MARCA = MO.ID_MARCA
LEFT JOIN RESERVA R ON V.ID_VEHICULO = R.ID_VEHICULO
WHERE R.ID_RESERVA IS NULL  -- EL "WHERE" ES PARA CONTROLAR: SOLO LOS QUE NO TIENEN PAREJA

ORDER BY MA.NOMBRE, V.PLACA  -- TOTAL REGISTROS 30
GO


---   -----          ------          -----


-- =====================================================================
-- CONSULTA 3: RIGHT JOIN
-- =====================================================================

/*
CONSULTA 3 (RIGHT JOIN):
LISTAR TODAS LAS SEDES DE RECOGIDA CON SU CIUDAD, EL NÚMERO DE ALQUILERES
FACTURADOS, EL TOTAL FACTURADO Y EL PROMEDIO POR FACTURA DE CADA SEDE.
LAS SEDES QUE NO HAN FACTURADO NADA TAMBIÉN DEBEN APARECER,
ORDENADO DEL MAYOR AL MENOR TOTAL FACTURADO

REGLA DEL CASO : LA RESERVA SE HACE "CON LA SEDE DE RECOGIDA" Y SE GENERA
                 FACTURA AL DEVOLVER EL VEHÍCULO.
BENEFICIO      : EL GERENTE VE QUÉ SEDES PRODUCEN INGRESOS Y CUÁLES NO
                 (NULL / 0), PARA DECIDIR DÓNDE PONER MÁS VEHÍCULOS O CERRAR PUNTOS.
POR QUÉ RIGHT  : PRIMERO SE UNEN RESERVA - ALQUILER - FACTURA (LO FACTURADO) Y
                 LUEGO SE TRAEN TODAS LAS SEDES, QUE ESTÁN A LA DERECHA.
                 ES LO MISMO QUE UN LEFT JOIN ESCRITO AL REVÉS.
TABLAS (4)     : RESERVA - ALQUILER - FACTURA - SEDE
RESULTADO ESPERADO: 50 REGISTROS (UNO POR SEDE): 12 CON INGRESOS Y 38 EN NULL
NOTA           : COUNT NO SE VIO EN CLASE; EL NÚMERO DE ALQUILERES SE CUENTA
                 SUMANDO 1 POR CADA FACTURA Y 0 CUANDO NO HAY (CASE + SUM).
*/

-- NECESITO RESERVA - ALQUILER - FACTURA - SEDE

SELECT S.NOMBRE AS SEDE, S.CIUDAD,
SUM(CASE WHEN F.ID_FACTURA IS NULL THEN 0 ELSE 1 END) AS NUMERO_ALQUILERES,
SUM(F.TOTAL) AS TOTAL_FACTURADO,
AVG(F.TOTAL) AS PROMEDIO_FACTURA

FROM RESERVA R  -- "R" es el alias de RESERVA
INNER JOIN ALQUILER A ON R.ID_RESERVA = A.ID_RESERVA  -- Se iguala PK con FK
INNER JOIN FACTURA F ON A.ID_ALQUILER = F.ID_ALQUILER
RIGHT JOIN SEDE S ON S.ID_SEDE = R.ID_SEDE  -- TODAS LAS SEDES (TABLA DE LA DERECHA), AUNQUE NO FACTUREN

GROUP BY S.ID_SEDE, S.NOMBRE, S.CIUDAD
ORDER BY TOTAL_FACTURADO DESC  -- TOTAL REGISTROS 50
GO

---- ---------

/*
CONSULTA 3B (PARA LA EXPOSICIÓN):
SOLO LAS SEDES QUE NO HAN FACTURADO NINGÚN ALQUILER
RESULTADO ESPERADO: 38 REGISTROS
*/

SELECT S.NOMBRE AS SEDE, S.CIUDAD, S.DIRECCION

FROM RESERVA R
INNER JOIN ALQUILER A ON R.ID_RESERVA = A.ID_RESERVA
INNER JOIN FACTURA F ON A.ID_ALQUILER = F.ID_ALQUILER
RIGHT JOIN SEDE S ON S.ID_SEDE = R.ID_SEDE
WHERE F.ID_FACTURA IS NULL  -- EL "WHERE" ES PARA CONTROLAR: SEDES SIN PAREJA

ORDER BY S.NOMBRE  -- TOTAL REGISTROS 38
GO


