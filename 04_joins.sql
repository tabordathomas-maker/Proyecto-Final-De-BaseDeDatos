-- =====================================================================
-- CONSULTA 4: FULL JOIN
-- =====================================================================

/*
CONSULTA 4 (FULL JOIN):
LISTAR EL USO DE LOS CONVENIOS CON EMPRESAS: TODAS LAS RESERVAS CON EL CÓDIGO,
EL CLIENTE Y LA FECHA DE INICIO, Y TODOS LOS CONVENIOS CON LA EMPRESA, EL TIPO
DE EMPRESA Y EL PORCENTAJE DE DESCUENTO. MOSTRAR EN UNA COLUMNA SI ES UNA
RESERVA CON CONVENIO, UNA RESERVA SIN CONVENIO O UN CONVENIO QUE NUNCA SE HA USADO,
ORDENADO POR ESA COLUMNA Y POR EMPRESA

REGLA DEL CASO : LOS CONVENIOS DAN DE 5 % A 10 % DE DESCUENTO; LA RESERVA PUEDE
                 TENER O NO CONVENIO (ID_CONVENIO ACEPTA NULL).
BENEFICIO      : EL ÁREA COMERCIAL VE EN UN SOLO REPORTE QUÉ CONVENIOS SE USAN,
                 CUÁLES NUNCA SE HAN USADO (PARA RENEGOCIARLOS) Y CUÁNTAS
                 RESERVAS SE HACEN SIN DESCUENTO.
POR QUÉ FULL   : SE NECESITAN LAS DOS PUNTAS SIN PAREJA: RESERVAS SIN CONVENIO
                 (NULL A LA DERECHA) Y CONVENIOS SIN RESERVAS (NULL A LA IZQUIERDA).
                 UN LEFT O UN RIGHT SOLO MOSTRARÍA UNA DE LAS DOS.
TABLAS (4)     : CLIENTE - RESERVA - CONVENIO - TIPO_EMPRESA
RESULTADO ESPERADO: 103 REGISTROS = 14 RESERVAS CON CONVENIO
                    + 52 RESERVAS SIN CONVENIO + 37 CONVENIOS SIN USAR
OJO            : TIPO_EMPRESA SE UNE CON LEFT JOIN. SI FUERA INNER JOIN, SE
                 PERDERÍAN LAS 52 RESERVAS SIN CONVENIO (SU CONVENIO ES NULL).
*/

-- NECESITO CLIENTE - RESERVA - CONVENIO - TIPO_EMPRESA

SELECT
CASE
	WHEN R.ID_RESERVA IS NULL THEN 'CONVENIO SIN USAR'
	WHEN CO.ID_CONVENIO IS NULL THEN 'RESERVA SIN CONVENIO'
	ELSE 'RESERVA CON CONVENIO'
END AS TIPO_REGISTRO,
R.CODIGO_RESERVA, UPPER(C.NOMBRES) AS NOMBRE_CLIENTE, R.FECHA_INICIO,
CO.EMPRESA, TE.NOMBRE AS TIPO_EMPRESA, CO.PORCENTAJE_DESCUENTO

FROM CLIENTE C  -- "C" es el alias de CLIENTE
INNER JOIN RESERVA R ON C.ID_CLIENTE = R.ID_CLIENTE  -- Se iguala PK con FK
FULL JOIN CONVENIO CO ON CO.ID_CONVENIO = R.ID_CONVENIO  -- TODAS LAS RESERVAS Y TODOS LOS CONVENIOS
LEFT JOIN TIPO_EMPRESA TE ON TE.ID_TIPO_EMPRESA = CO.ID_TIPO_EMPRESA  -- LEFT PARA NO PERDER LAS RESERVAS SIN CONVENIO

ORDER BY TIPO_REGISTRO, CO.EMPRESA, R.CODIGO_RESERVA  -- TOTAL REGISTROS 103
GO

---- ---------

/*
CONSULTA 4B (PARA LA EXPOSICIÓN):
SOLO LOS CONVENIOS QUE NUNCA SE HAN USADO EN UNA RESERVA
RESULTADO ESPERADO: 37 REGISTROS
*/

SELECT CO.EMPRESA, TE.NOMBRE AS TIPO_EMPRESA, CO.PORCENTAJE_DESCUENTO

FROM CLIENTE C
INNER JOIN RESERVA R ON C.ID_CLIENTE = R.ID_CLIENTE
FULL JOIN CONVENIO CO ON CO.ID_CONVENIO = R.ID_CONVENIO
LEFT JOIN TIPO_EMPRESA TE ON TE.ID_TIPO_EMPRESA = CO.ID_TIPO_EMPRESA
WHERE R.ID_RESERVA IS NULL  -- EL "WHERE" ES PARA CONTROLAR: CONVENIOS SIN PAREJA

ORDER BY CO.EMPRESA  -- TOTAL REGISTROS 37
GO
