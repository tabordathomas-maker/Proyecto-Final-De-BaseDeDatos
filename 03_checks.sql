/*
CHECK 29:
VALIDAR LA MULTA POR CANCELACIÓN: GRATIS HASTA 24 HORAS ANTES

REGLA DEL CASO: CANCELAR ES GRATIS HASTA 24 H ANTES; DESPUÉS, LA MULTA ES DE 1 DÍA DE ALQUILER.
BENEFICIO     : NO SE COBRA A QUIEN CANCELÓ A TIEMPO NI SE PERDONA A QUIEN CANCELÓ TARDE (24 H = 1.440 MINUTOS).
RECHAZA       : CANCELÓ 3 DÍAS ANTES Y VALOR_MULTA = 90000; CANCELÓ 2 H ANTES Y VALOR_MULTA = 0
*/
ALTER TABLE RESERVA   -- TABLA DONDE SE APLICA LA REGLA
ADD CONSTRAINT CK_RESERVA_CANCELACION_GRATIS   -- NOMBRE DE LA RESTRICCIÓN
CHECK   -- CONDICIÓN QUE DEBE CUMPLIR CADA FILA
(ESTADO <> 'CANCELADA'
 OR (DATEDIFF(MINUTE, FECHA_CANCELACION, FECHA_INICIO) >= 1440 AND VALOR_MULTA = 0)
 OR (DATEDIFF(MINUTE, FECHA_CANCELACION, FECHA_INICIO) <  1440 AND VALOR_MULTA > 0))
GO

--- ----        -----

/*
CHECK 30:
VALIDAR QUE LAS FECHAS DEL ALQUILER SEAN COHERENTES

REGLA DEL CASO: EL ALQUILER REGISTRA ENTREGA, FIN PACTADO Y DEVOLUCIÓN.
BENEFICIO     : EL CÁLCULO DEL RETRASO (1 DÍA LAS PRIMERAS 24 H, LUEGO EL DOBLE) NECESITA FECHAS COHERENTES.
RECHAZA       : FECHA_DEVOLUCION ANTERIOR A FECHA_ENTREGA
*/
ALTER TABLE ALQUILER   -- TABLA DONDE SE APLICA LA REGLA
ADD CONSTRAINT CK_ALQUILER_FECHAS   -- NOMBRE DE LA RESTRICCIÓN
CHECK   -- CONDICIÓN QUE DEBE CUMPLIR CADA FILA
(FECHA_FIN_PACTADA > FECHA_ENTREGA
 AND (FECHA_DEVOLUCION IS NULL OR FECHA_DEVOLUCION > FECHA_ENTREGA))
GO

--- ----        -----

/*
CHECK 31:
VALIDAR EL ANTICIPO Y EL VALOR TOTAL DEL ALQUILER

REGLA DEL CASO: AL ENTREGAR SE COBRA UN ANTICIPO; AL DEVOLVER SE RECALCULA EL VALOR TOTAL.
BENEFICIO     : SIN VALORES NEGATIVOS; EL TOTAL NUNCA ES MENOR QUE EL ANTICIPO YA PAGADO.
RECHAZA       : ANTICIPO = 500000 Y VALOR_TOTAL = 300000
*/
ALTER TABLE ALQUILER   -- TABLA DONDE SE APLICA LA REGLA
ADD CONSTRAINT CK_ALQUILER_VALORES   -- NOMBRE DE LA RESTRICCIÓN
CHECK (ANTICIPO >= 0 AND (VALOR_TOTAL IS NULL OR VALOR_TOTAL >= ANTICIPO))   -- CONDICIÓN QUE DEBE CUMPLIR CADA FILA
GO

--- ----        -----

/*
CHECK 32:
VALIDAR EL NIVEL DE GASOLINA Y EL KILOMETRAJE DEL ACTA

REGLA DEL CASO: EL ACTA REGISTRA KILOMETRAJE Y NIVEL DE GASOLINA; SE COBRA SI EL TANQUE NO ESTÁ LLENO.
BENEFICIO     : NIVEL EN PORCENTAJE (0 A 100), COMPARABLE CONTRA EL TANQUE LLENO (100).
RECHAZA       : NIVEL_GASOLINA = 120
*/
ALTER TABLE INSPECCION   -- TABLA DONDE SE APLICA LA REGLA
ADD CONSTRAINT CK_INSPECCION_GASOLINA_KM   -- NOMBRE DE LA RESTRICCIÓN
CHECK (NIVEL_GASOLINA BETWEEN 0 AND 100 AND KILOMETRAJE >= 0)   -- CONDICIÓN QUE DEBE CUMPLIR CADA FILA
GO

--- ----        -----

/*
CHECK 33:
VALIDAR EL VALOR Y LA DESCRIPCIÓN DEL DAÑO

REGLA DEL CASO: LOS DAÑOS SE VALORAN Y SE COBRAN EN LA FACTURA.
BENEFICIO     : VALOR NO NEGATIVO Y DESCRIPCIÓN OBLIGATORIA COMO SOPORTE ANTE UN RECLAMO.
RECHAZA       : VALOR = -50000 O DESCRIPCION VACÍA
*/
ALTER TABLE DANIO   -- TABLA DONDE SE APLICA LA REGLA
ADD CONSTRAINT CK_DANIO_VALOR   -- NOMBRE DE LA RESTRICCIÓN
CHECK (VALOR >= 0 AND DESCRIPCION IS NOT NULL AND LEN(DESCRIPCION) > 0)   -- CONDICIÓN QUE DEBE CUMPLIR CADA FILA
GO

--- ----        -----

/*
CHECK 34:
VALIDAR QUE LAS CALIFICACIONES ESTÉN ENTRE 1 Y 5

REGLA DEL CASO: ENCUESTA DE SATISFACCIÓN DEL SERVICIO Y DEL VEHÍCULO.
BENEFICIO     : ESCALA FIJA DE 1 A 5: LOS PROMEDIOS DEL HISTORIAL DEL VEHÍCULO TIENEN SENTIDO.
RECHAZA       : CALIF_SERVICIO = 10
*/
ALTER TABLE ENCUESTA   -- TABLA DONDE SE APLICA LA REGLA
ADD CONSTRAINT CK_ENCUESTA_CALIFICACIONES   -- NOMBRE DE LA RESTRICCIÓN
CHECK (CALIF_SERVICIO BETWEEN 1 AND 5 AND CALIF_VEHICULO BETWEEN 1 AND 5)   -- CONDICIÓN QUE DEBE CUMPLIR CADA FILA
GO

--- ----        -----


-- =====================================================================
-- BLOQUE 5: FACTURA Y PAGOS (DETALLE_FACTURA, PAGO, PAGO_TARJETA, PAGO_EFECTIVO)
-- =====================================================================

/*
CHECK 35:
VALIDAR LOS CONCEPTOS QUE SE PUEDEN COBRAR EN LA FACTURA

REGLA DEL CASO: AL DEVOLVER SE RECALCULA: RETRASO, EXCESO DE KM, GASOLINA, DAÑOS Y DESCUENTO.
BENEFICIO     : CADA LÍNEA DE LA FACTURA SE RASTREA A UNA REGLA DEL CASO.
RECHAZA       : CONCEPTO = 'OTROS'
*/
ALTER TABLE DETALLE_FACTURA   -- TABLA DONDE SE APLICA LA REGLA
ADD CONSTRAINT CK_DETALLE_FACTURA_CONCEPTO   -- NOMBRE DE LA RESTRICCIÓN
CHECK   -- CONDICIÓN QUE DEBE CUMPLIR CADA FILA
(CONCEPTO IN ('ALQUILER', 'POLIZA', 'RETRASO', 'EXCESO_KM', 'COMBUSTIBLE',
              'DANIO', 'MULTA_CANCELACION', 'DESCUENTO_CONVENIO'))
GO

--- ----        -----

/*
CHECK 36:
VALIDAR QUE SOLO EL DESCUENTO DE CONVENIO SEA NEGATIVO

REGLA DEL CASO: EL DESCUENTO DE CONVENIO SE RESTA (SIN INCLUIR MULTAS).
BENEFICIO     : EL DESCUENTO ES LA ÚNICA LÍNEA NEGATIVA; NINGÚN COBRO SE CUELA COMO DESCUENTO.
RECHAZA       : CONCEPTO = 'DANIO' CON VALOR = -100000
*/
ALTER TABLE DETALLE_FACTURA   -- TABLA DONDE SE APLICA LA REGLA
ADD CONSTRAINT CK_DETALLE_FACTURA_VALOR   -- NOMBRE DE LA RESTRICCIÓN
CHECK   -- CONDICIÓN QUE DEBE CUMPLIR CADA FILA
((CONCEPTO = 'DESCUENTO_CONVENIO' AND VALOR < 0)
 OR (CONCEPTO <> 'DESCUENTO_CONVENIO' AND VALOR >= 0))
GO

--- ----        -----

/*
CHECK 37:
VALIDAR EL VALOR Y LA MONEDA DEL PAGO

REGLA DEL CASO: EL CAJERO REGISTRA EL PAGO EN COP, USD O EUR.
BENEFICIO     : NO HAY PAGOS EN 0 QUE 'CUADREN' FACTURAS SIN DINERO; MONEDA COHERENTE CON LA TRM.
RECHAZA       : VALOR = 0, MONEDA = 'BTC'
*/
ALTER TABLE PAGO   -- TABLA DONDE SE APLICA LA REGLA
ADD CONSTRAINT CK_PAGO_VALOR_MONEDA   -- NOMBRE DE LA RESTRICCIÓN
CHECK (VALOR > 0 AND MONEDA IN ('COP', 'USD', 'EUR'))   -- CONDICIÓN QUE DEBE CUMPLIR CADA FILA
GO

--- ----        -----

/*
CHECK 38:
VALIDAR LOS DATOS DEL PAGO CON TARJETA

REGLA DEL CASO: PAGO CON LA TARJETA REGISTRADA U OTRA TARJETA.
BENEFICIO     : ÉTICA (SOLO 4 DÍGITOS) Y CONCILIACIÓN CON EL BANCO POR FRANQUICIA.
RECHAZA       : ULTIMOS4 = '12AB', FRANQUICIA = 'TARJETA AZUL'
*/
ALTER TABLE PAGO_TARJETA   -- TABLA DONDE SE APLICA LA REGLA
ADD CONSTRAINT CK_PAGO_TARJETA_DATOS   -- NOMBRE DE LA RESTRICCIÓN
CHECK   -- CONDICIÓN QUE DEBE CUMPLIR CADA FILA
(ULTIMOS4 LIKE '[0-9][0-9][0-9][0-9]'
 AND FRANQUICIA IN ('VISA', 'MASTERCARD', 'AMERICAN_EXPRESS', 'DINERS'))
GO

--- ----        -----

/*
CHECK 39:
VALIDAR EL VALOR RECIBIDO Y EL CAMBIO DEL PAGO EN EFECTIVO

REGLA DEL CASO: PAGO EN EFECTIVO EN LA CAJA.
BENEFICIO     : CUADRE DE CAJA: EL CAMBIO NUNCA ES NEGATIVO NI MAYOR QUE LO RECIBIDO.
RECHAZA       : VALOR_RECIBIDO = 100000 Y CAMBIO = -20000
*/
ALTER TABLE PAGO_EFECTIVO   -- TABLA DONDE SE APLICA LA REGLA
ADD CONSTRAINT CK_PAGO_EFECTIVO_VALORES   -- NOMBRE DE LA RESTRICCIÓN
CHECK (VALOR_RECIBIDO > 0 AND CAMBIO >= 0 AND CAMBIO < VALOR_RECIBIDO)   -- CONDICIÓN QUE DEBE CUMPLIR CADA FILA
GO

--- ----        -----


-- =====================================================================
-- VERIFICACIÓN: LISTAR TODOS LOS CHECK CREADOS (PARA MOSTRAR EN LA EXPOSICIÓN)
-- =====================================================================

/*
CONSULTA DE VERIFICACIÓN:
LISTAR LAS RESTRICCIONES CHECK DE LA BASE DE DATOS CON SU TABLA Y SU CONDICIÓN.
RESULTADO ESPERADO: 39 FILAS.
*/

SELECT OBJECT_NAME(CC.parent_object_id) AS TABLA,
       CC.[name]                        AS RESTRICCION,
       CC.[definition]                  AS CONDICION
FROM SYS.check_constraints CC   -- CC es el alias de SYS.check_constraints
ORDER BY TABLA, RESTRICCION
GO


