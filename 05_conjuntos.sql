-- =====================================================================
-- CONSULTA 4: INTERSECT CON GROUP BY Y HAVING
-- =====================================================================

/*
CONSULTA 4 (INTERSECT CON HAVING):
LISTAR LOS CLIENTES DE ALTO VALOR QUE QUEDARON INSATISFECHOS: LOS QUE EN TOTAL HAN
PAGADO MÁS DE 5.000.000 DE PESOS EN FACTURAS Y QUE ADEMÁS CALIFICARON CON 3 O MENOS
EL SERVICIO O EL VEHÍCULO EN LA ENCUESTA DE SATISFACCIÓN,
ORDENADO POR NOMBRE

REGLA DEL CASO : "SE GENERA LA FACTURA" Y "ENCUESTA DE SATISFACCIÓN SOBRE EL
                 SERVICIO Y EL VEHÍCULO".
BENEFICIO      : SON LOS CLIENTES QUE MÁS DINERO DEJAN Y QUE LA EMPRESA PUEDE
                 PERDER. EL GERENTE LOS LLAMA PRIMERO PARA RETENERLOS.
POR QUÉ INTERSECT + HAVING: EL GRUPO A SE ARMA CON SUM DE TODAS LAS FACTURAS DEL
                 CLIENTE (UN CLIENTE PUEDE TENER VARIOS ALQUILERES), POR ESO VA
                 GROUP BY + HAVING, COMO EN LA CLASE DEL 14-10. LUEGO SE CRUZA
                 CON EL GRUPO B (MALAS CALIFICACIONES).
TABLAS (5)     : CLIENTE - RESERVA - ALQUILER - FACTURA
                 Y CLIENTE - RESERVA - ALQUILER - ENCUESTA
RESULTADO ESPERADO: 4 REGISTROS
*/

-- NECESITO CLIENTE - RESERVA - ALQUILER - FACTURA (TOTAL)
-- Y TAMBIÉN CLIENTE - RESERVA - ALQUILER - ENCUESTA (CALIFICACIONES)

SELECT C.ID_CLIENTE, UPPER(C.NOMBRES) AS NOMBRE_CLIENTE
FROM CLIENTE C  -- "C" es el alias de CLIENTE
INNER JOIN RESERVA R ON C.ID_CLIENTE = R.ID_CLIENTE  -- Se iguala PK con FK
INNER JOIN ALQUILER A ON R.ID_RESERVA = A.ID_RESERVA
INNER JOIN FACTURA F ON A.ID_ALQUILER = F.ID_ALQUILER
GROUP BY C.ID_CLIENTE, C.NOMBRES
HAVING SUM(F.TOTAL) > 5000000  -- TOTAL REGISTROS 6 CLIENTES DE ALTO VALOR

INTERSECT

SELECT C.ID_CLIENTE, UPPER(C.NOMBRES) AS NOMBRE_CLIENTE
FROM CLIENTE C
INNER JOIN RESERVA R ON C.ID_CLIENTE = R.ID_CLIENTE
INNER JOIN ALQUILER A ON R.ID_RESERVA = A.ID_RESERVA
INNER JOIN ENCUESTA E ON A.ID_ALQUILER = E.ID_ALQUILER
WHERE E.CALIF_SERVICIO <= 3 OR E.CALIF_VEHICULO <= 3  -- TOTAL REGISTROS 8 (UNO POR ENCUESTA) = 7 CLIENTES SIN REPETIR

ORDER BY NOMBRE_CLIENTE  -- TOTAL REGISTROS 4 (ALTO VALOR E INSATISFECHOS)
GO

---- ---------

/*
CONSULTA 4B (PARA LA EXPOSICIÓN):
VER EL TOTAL PAGADO Y LAS CALIFICACIONES DE ESOS 4 CLIENTES, PARA EXPLICAR POR QUÉ
SALIERON EN LA CONSULTA 4
RESULTADO ESPERADO: 5 REGISTROS (LA CLIENTE 92 DIO 2 ENCUESTAS MALAS)
*/

SELECT C.ID_CLIENTE, UPPER(C.NOMBRES) AS NOMBRE_CLIENTE,
E.CALIF_SERVICIO, E.CALIF_VEHICULO, F.TOTAL AS TOTAL_FACTURA
FROM CLIENTE C
INNER JOIN RESERVA R ON C.ID_CLIENTE = R.ID_CLIENTE
INNER JOIN ALQUILER A ON R.ID_RESERVA = A.ID_RESERVA
INNER JOIN ENCUESTA E ON A.ID_ALQUILER = E.ID_ALQUILER
INNER JOIN FACTURA F ON A.ID_ALQUILER = F.ID_ALQUILER
WHERE C.ID_CLIENTE IN (56, 61, 92, 100)  -- LOS 4 CLIENTES QUE DIO LA CONSULTA 4
AND (E.CALIF_SERVICIO <= 3 OR E.CALIF_VEHICULO <= 3)  -- EL "WHERE" ES PARA CONTROLAR

ORDER BY NOMBRE_CLIENTE  -- TOTAL REGISTROS 5
GO
