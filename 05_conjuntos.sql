-- =====================================================================
-- CONSULTA 2: INTERSECT
-- =====================================================================

/*
CONSULTA 2 (INTERSECT):
LISTAR LOS VEHÍCULOS (ID, PLACA, MARCA Y MODELO) QUE TIENEN DAÑOS REGISTRADOS EN
LAS ACTAS DE INSPECCIÓN DE SUS ALQUILERES Y QUE ADEMÁS TIENEN UNA REPARACIÓN EN SU
HOJA DE VIDA (MANTENIMIENTOS DE TIPO "REPARACION"),
ORDENADO POR PLACA

REGLA DEL CASO : "INSPECCIÓN CON FOTOS ... DAÑOS" Y "HOJA DE VIDA DEL VEHÍCULO:
                 MANTENIMIENTOS Y REPARACIONES CON COSTO Y TALLER".
BENEFICIO      : EL GERENTE VE QUÉ VEHÍCULOS SE DAÑAN EN LOS ALQUILERES Y YA HAN
                 IDO AL TALLER: CANDIDATOS A REVISIÓN A FONDO O A SALIR DE LA FLOTA.
POR QUÉ INTERSECT: SOLO INTERESAN LOS VEHÍCULOS QUE ESTÁN EN LOS DOS GRUPOS A LA
                 VEZ (CON DAÑOS Y CON REPARACIÓN).
TABLAS (8)     : VEHICULO - MODELO - MARCA - RESERVA - ALQUILER - INSPECCION - DANIO
                 Y VEHICULO - MODELO - MARCA - MANTENIMIENTO - TIPO_MANTENIMIENTO
RESULTADO ESPERADO: 5 REGISTROS
*/

-- NECESITO VEHICULO - MODELO - MARCA - RESERVA - ALQUILER - INSPECCION - DANIO
-- Y TAMBIÉN VEHICULO - MODELO - MARCA - MANTENIMIENTO - TIPO_MANTENIMIENTO

SELECT V.ID_VEHICULO, V.PLACA, MA.NOMBRE AS MARCA, MO.NOMBRE AS MODELO
FROM VEHICULO V  -- "V" es el alias de VEHICULO
INNER JOIN MODELO MO ON MO.ID_MODELO = V.ID_MODELO  -- Se iguala PK con FK
INNER JOIN MARCA MA ON MA.ID_MARCA = MO.ID_MARCA
INNER JOIN RESERVA R ON V.ID_VEHICULO = R.ID_VEHICULO
INNER JOIN ALQUILER A ON R.ID_RESERVA = A.ID_RESERVA
INNER JOIN INSPECCION I ON A.ID_ALQUILER = I.ID_ALQUILER
INNER JOIN DANIO D ON I.ID_INSPECCION = D.ID_INSPECCION  -- TOTAL REGISTROS 53 (UNO POR DAÑO) = 19 VEHÍCULOS SIN REPETIR

INTERSECT

SELECT V.ID_VEHICULO, V.PLACA, MA.NOMBRE AS MARCA, MO.NOMBRE AS MODELO
FROM VEHICULO V
INNER JOIN MODELO MO ON MO.ID_MODELO = V.ID_MODELO
INNER JOIN MARCA MA ON MA.ID_MARCA = MO.ID_MARCA
INNER JOIN MANTENIMIENTO M ON V.ID_VEHICULO = M.ID_VEHICULO
INNER JOIN TIPO_MANTENIMIENTO TM ON TM.ID_TIPO_MANTENIMIENTO = M.ID_TIPO_MANTENIMIENTO
WHERE TM.NOMBRE LIKE 'REPARACION%'  -- Busca al principio con REPARACION -- TOTAL REGISTROS 18 (UNO POR REPARACIÓN) = 16 VEHÍCULOS SIN REPETIR

ORDER BY PLACA  -- TOTAL REGISTROS 5 (ESTÁN EN LOS DOS GRUPOS)
GO


