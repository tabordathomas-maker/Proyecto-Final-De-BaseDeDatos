-- =====================================================================
-- CONSULTA 3: EXCEPT
-- =====================================================================

/*
CONSULTA 3 (EXCEPT):
LISTAR LOS CLIENTES QUE HAN ALQUILADO VEHÍCULOS DE GAMA ALTA PERO NUNCA HAN TOMADO
LA PÓLIZA PREMIUM (CUBRIMIENTO TOTAL). MOSTRAR EL ID, EL NOMBRE EN MAYÚSCULAS Y EL
CORREO DEL CLIENTE,
ORDENADO POR NOMBRE

REGLA DEL CASO : "LA TARIFA DEPENDE DE LA GAMA Y LA PÓLIZA: BÁSICA, INTERMEDIA Y
                 PREMIUM (CUBRIMIENTO TOTAL)".
BENEFICIO      : EL ÁREA COMERCIAL LES OFRECE LA PÓLIZA PREMIUM A QUIENES MANEJAN
                 LOS CARROS MÁS CAROS SIN CUBRIMIENTO TOTAL: MÁS VENTAS Y MENOS
                 RIESGO PARA LA EMPRESA.
POR QUÉ EXCEPT : SE QUIEREN LOS DEL GRUPO A (GAMA ALTA) QUE NO ESTÁN EN EL GRUPO B
                 (PÓLIZA PREMIUM). ES UNA RESTA: A - B.
TABLAS (5)     : USUARIO - CLIENTE - RESERVA - ALQUILER - VEHICULO
                 Y USUARIO - CLIENTE - RESERVA - ALQUILER - POLIZA
RESULTADO ESPERADO: 9 REGISTROS
*/

-- NECESITO USUARIO (CORREO) - CLIENTE - RESERVA - ALQUILER - VEHICULO (GAMA)
-- Y TAMBIÉN USUARIO - CLIENTE - RESERVA - ALQUILER - POLIZA (NOMBRE)

SELECT C.ID_CLIENTE, UPPER(C.NOMBRES) AS NOMBRE_CLIENTE, U.CORREO
FROM CLIENTE C  -- "C" es el alias de CLIENTE
INNER JOIN USUARIO U ON U.ID_USUARIO = C.ID_CLIENTE  -- ESPECIALIZACIÓN: EL CLIENTE ES UN USUARIO
INNER JOIN RESERVA R ON C.ID_CLIENTE = R.ID_CLIENTE  -- Se iguala PK con FK
INNER JOIN ALQUILER A ON R.ID_RESERVA = A.ID_RESERVA  -- SOLO RESERVAS QUE SE VOLVIERON ALQUILER
INNER JOIN VEHICULO V ON V.ID_VEHICULO = R.ID_VEHICULO
WHERE V.GAMA = 'ALTA'  -- TOTAL REGISTROS 15 (UNO POR ALQUILER) = 13 CLIENTES SIN REPETIR (GRUPO A)

EXCEPT

SELECT C.ID_CLIENTE, UPPER(C.NOMBRES) AS NOMBRE_CLIENTE, U.CORREO
FROM CLIENTE C
INNER JOIN USUARIO U ON U.ID_USUARIO = C.ID_CLIENTE
INNER JOIN RESERVA R ON C.ID_CLIENTE = R.ID_CLIENTE
INNER JOIN ALQUILER A ON R.ID_RESERVA = A.ID_RESERVA
INNER JOIN POLIZA P ON P.ID_POLIZA = R.ID_POLIZA
WHERE P.NOMBRE = 'PREMIUM'  -- TOTAL REGISTROS 12 (UNO POR ALQUILER) = 9 CLIENTES SIN REPETIR (GRUPO B)

ORDER BY NOMBRE_CLIENTE  -- TOTAL REGISTROS 9 (A - B)
GO

---- ---------

/*
CONSULTA 3B (EXCEPT INVERTIDO, PARA LA EXPOSICIÓN):
LOS CLIENTES QUE SÍ TOMARON LA PÓLIZA PREMIUM PERO NUNCA HAN ALQUILADO UN VEHÍCULO
DE GAMA ALTA (B - A). COMO EN LA CLASE DEL 14-10: AL INTERCAMBIAR LOS GRUPOS DEL
EXCEPT APARECEN "LOS QUE FALTAN"; ES COMO PASAR DE UN LEFT JOIN A UN RIGHT JOIN.
BENEFICIO: CLIENTES QUE YA PAGAN COBERTURA TOTAL; SE LES PUEDE OFRECER SUBIR A
GAMA ALTA.
RESULTADO ESPERADO: 5 REGISTROS
*/

SELECT C.ID_CLIENTE, UPPER(C.NOMBRES) AS NOMBRE_CLIENTE, U.CORREO
FROM CLIENTE C
INNER JOIN USUARIO U ON U.ID_USUARIO = C.ID_CLIENTE
INNER JOIN RESERVA R ON C.ID_CLIENTE = R.ID_CLIENTE
INNER JOIN ALQUILER A ON R.ID_RESERVA = A.ID_RESERVA
INNER JOIN POLIZA P ON P.ID_POLIZA = R.ID_POLIZA
WHERE P.NOMBRE = 'PREMIUM'  -- TOTAL REGISTROS 12 (UNO POR ALQUILER) = 9 CLIENTES SIN REPETIR (GRUPO B)

EXCEPT

SELECT C.ID_CLIENTE, UPPER(C.NOMBRES) AS NOMBRE_CLIENTE, U.CORREO
FROM CLIENTE C
INNER JOIN USUARIO U ON U.ID_USUARIO = C.ID_CLIENTE
INNER JOIN RESERVA R ON C.ID_CLIENTE = R.ID_CLIENTE
INNER JOIN ALQUILER A ON R.ID_RESERVA = A.ID_RESERVA
INNER JOIN VEHICULO V ON V.ID_VEHICULO = R.ID_VEHICULO
WHERE V.GAMA = 'ALTA'  -- TOTAL REGISTROS 15 (UNO POR ALQUILER) = 13 CLIENTES SIN REPETIR (GRUPO A)

ORDER BY NOMBRE_CLIENTE  -- TOTAL REGISTROS 5 (B - A)
GO

---- ---------

-- PARA SUSTENTAR: ¿CUADRAN LAS CUENTAS?
-- GRUPO A (GAMA ALTA) = 13 CLIENTES
-- A - B (CONSULTA 3) = 9   +   A INTERSECT B (ABAJO) = 4   ->   9 + 4 = 13  OK
-- GRUPO B (PREMIUM)   = 9 CLIENTES
-- B - A (CONSULTA 3B) = 5  +   A INTERSECT B (ABAJO) = 4   ->   5 + 4 = 9   OK

SELECT C.ID_CLIENTE, UPPER(C.NOMBRES) AS NOMBRE_CLIENTE, U.CORREO
FROM CLIENTE C
INNER JOIN USUARIO U ON U.ID_USUARIO = C.ID_CLIENTE
INNER JOIN RESERVA R ON C.ID_CLIENTE = R.ID_CLIENTE
INNER JOIN ALQUILER A ON R.ID_RESERVA = A.ID_RESERVA
INNER JOIN VEHICULO V ON V.ID_VEHICULO = R.ID_VEHICULO
WHERE V.GAMA = 'ALTA'

INTERSECT

SELECT C.ID_CLIENTE, UPPER(C.NOMBRES) AS NOMBRE_CLIENTE, U.CORREO
FROM CLIENTE C
INNER JOIN USUARIO U ON U.ID_USUARIO = C.ID_CLIENTE
INNER JOIN RESERVA R ON C.ID_CLIENTE = R.ID_CLIENTE
INNER JOIN ALQUILER A ON R.ID_RESERVA = A.ID_RESERVA
INNER JOIN POLIZA P ON P.ID_POLIZA = R.ID_POLIZA
WHERE P.NOMBRE = 'PREMIUM'

ORDER BY NOMBRE_CLIENTE  -- TOTAL REGISTROS 4 (EN LOS DOS GRUPOS)
GO


