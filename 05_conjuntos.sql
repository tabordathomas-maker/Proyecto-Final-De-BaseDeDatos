-- =====================================================================
-- CONSULTA 1: UNION
-- =====================================================================

/*
CONSULTA 1 (UNION):
LISTAR LOS CLIENTES QUE DEBE REVISAR EL ÁREA DE CARTERA: LOS QUE ESTÁN EN ESTADO
MOROSO O VETADO, Y LOS QUE HAN CANCELADO ALGUNA RESERVA. MOSTRAR EL ID, EL NOMBRE
EN MAYÚSCULAS Y EL ESTADO DEL CLIENTE, SIN REPETIR CLIENTES,
ORDENADO POR ESTADO Y POR NOMBRE

REGLA DEL CASO : "CLIENTE MOROSO NO PUEDE RESERVAR, VETADO NO PUEDE INGRESAR" Y
                 "LA CANCELACIÓN DESPUÉS DE 24 H TIENE MULTA DE 1 DÍA".
BENEFICIO      : EL GERENTE TIENE EN UNA SOLA LISTA A TODOS LOS CLIENTES DE
                 RIESGO PARA LLAMARLOS, COBRARLES O REVISAR SU ESTADO.
POR QUÉ UNION  : SON DOS GRUPOS DISTINTOS (POR ESTADO Y POR CANCELACIÓN) Y SE
                 QUIEREN TODOS JUNTOS. EL UNION QUITA LOS REPETIDOS: LA CLIENTE
                 92 ES MOROSA Y ADEMÁS CANCELÓ, PERO SALE UNA SOLA VEZ.
TABLAS         : CLIENTE - RESERVA
RESULTADO ESPERADO: 6 + 8 = 14, MENOS 1 REPETIDO = 13 REGISTROS
*/

-- NECESITO CLIENTE (ESTADO) - RESERVA (ESTADO = 'CANCELADA')

SELECT C.ID_CLIENTE, UPPER(C.NOMBRES) AS NOMBRE_CLIENTE, C.ESTADO AS ESTADO_CLIENTE
FROM CLIENTE C  -- "C" es el alias de CLIENTE
WHERE C.ESTADO IN ('MOROSO', 'VETADO')  -- TOTAL REGISTROS 6

UNION

SELECT C.ID_CLIENTE, UPPER(C.NOMBRES) AS NOMBRE_CLIENTE, C.ESTADO AS ESTADO_CLIENTE
FROM CLIENTE C
INNER JOIN RESERVA R ON C.ID_CLIENTE = R.ID_CLIENTE  -- Se iguala PK con FK
WHERE R.ESTADO = 'CANCELADA'  -- TOTAL REGISTROS 8

ORDER BY ESTADO_CLIENTE, NOMBRE_CLIENTE  -- TOTAL REGISTROS 13 (UNIDOS SIN REPETIDOS)
GO


