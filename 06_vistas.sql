CREATE VIEW VW_CATALOGO_DISPONIBLES
AS
SELECT V.ID_VEHICULO, V.PLACA,
MA.NOMBRE AS MARCA, MO.NOMBRE AS MODELO,
V.GAMA, V.CAPACIDAD, V.PUERTAS, V.TRANSMISION, V.COMBUSTIBLE, V.CONSUMO,
V.KILOMETRAJE, V.COLOR, V.CATEGORIA_LICENCIA AS LICENCIA_REQUERIDA,
V.ESTADO, MV.URL AS FOTO_FRONTAL

FROM VEHICULO V  -- "V" es el alias de VEHICULO
INNER JOIN MODELO MO ON MO.ID_MODELO = V.ID_MODELO  -- Se iguala PK con FK
INNER JOIN MARCA MA ON MA.ID_MARCA = MO.ID_MARCA
INNER JOIN MULTIMEDIA_VEHICULO MV ON V.ID_VEHICULO = MV.ID_VEHICULO
INNER JOIN TIPO_MULTIMEDIA TM ON TM.ID_TIPO_MULTIMEDIA = MV.ID_TIPO_MULTIMEDIA

WHERE V.ESTADO = 'DISPONIBLE'       -- SOLO LOS QUE SE PUEDEN RESERVAR
AND V.ES_RESPALDO = 0               -- EL STOCK DE RESPALDO NO SE PUEDE RESERVAR
AND TM.NOMBRE = 'FOTO - FRONTAL'    -- UNA SOLA FOTO POR VEHÍCULO (ASÍ NO SE REPITEN FILAS)
