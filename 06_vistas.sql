CREATE FUNCTION FN_CATALOGO_POR_GAMA
(
@GAMA VARCHAR(45)
)
RETURNS TABLE
AS
RETURN
(
	SELECT TOP(100) CD.PLACA, UPPER(CD.MARCA) AS MARCA, CD.MODELO, CD.GAMA,
	CD.CAPACIDAD, CD.TRANSMISION, CD.COMBUSTIBLE, CD.KILOMETRAJE, CD.COLOR,
	CD.LICENCIA_REQUERIDA, CD.FOTO_FRONTAL
	FROM VW_CATALOGO_DISPONIBLES CD  -- LA FUNCIÓN EJECUTA LA VISTA
	WHERE CD.GAMA = @GAMA
	ORDER BY CD.MARCA, CD.KILOMETRAJE  -- CON ORDER BY VA EL TOP, COMO EN CLASE
)
GO

