/*
DEMO 3:
MODIFICAR UNA RESERVA A TRAVÉS DE LA VISTA 2 (TERMINA EN ROLLBACK)

LA CLIENTE DE LA RESERVA RV2611015101 (RECOGE EL 12-11-2026 EN EL AEROPUERTO
JOSE MARIA CORDOVA) PIDE RECOGER EN LA SEDE PRINCIPAL (ID_SEDE = 1).
EL UPDATE SOLO TOCA COLUMNAS DE RESERVA (ID_SEDE Y ESTADO) -> SE PERMITE.

RESULTADO ESPERADO: SEDE_RECOGIDA PASA DE 'PUNTO AEROPUERTO JOSE MARIA CORDOVA'
