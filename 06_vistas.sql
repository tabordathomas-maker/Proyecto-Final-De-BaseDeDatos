/*
DEMO 1:
ACTUALIZAR DATOS A TRAVÉS DE LA VISTA 1 (SIN DAÑAR LOS DATOS: TERMINA EN ROLLBACK)

PASO 1: UPDATE QUE SOLO TOCA LA TABLA VEHICULO (KILOMETRAJE Y COLOR DEL WGU959).
PASO 2: UPDATE QUE SOLO TOCA LA TABLA MULTIMEDIA_VEHICULO (LA FOTO FRONTAL).
