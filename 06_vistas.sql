-- Description:	<FUNCIÓN DE TABLA 2 - EJECUTA LA VISTA VW_AGENDA_RESERVAS POR SEDE>
-- =============================================
CREATE FUNCTION FN_AGENDA_POR_SEDE
(
@ID_SEDE INT
)
RETURNS TABLE
AS
RETURN
(
	SELECT TOP(100) AR.CODIGO_RESERVA, AR.SEDE_RECOGIDA,
	UPPER(AR.NOMBRE_CLIENTE) AS NOMBRE_CLIENTE,
	AR.LICENCIA_CLIENTE, AR.LICENCIA_REQUERIDA,
	AR.PLACA, AR.MARCA, AR.MODELO,
	AR.FECHA_INICIO,
	DATENAME(WEEKDAY, AR.FECHA_INICIO) AS NOMBRE_DIA,
	DATENAME(MONTH, AR.FECHA_INICIO) AS NOMBRE_MES,
	DATEDIFF(DAY, GETDATE(), AR.FECHA_INICIO) AS DIAS_PARA_ENTREGA,
	AR.DIAS_ALQUILER, AR.POLIZA, AR.MODALIDAD
	FROM VW_AGENDA_RESERVAS AR  -- LA FUNCIÓN EJECUTA LA VISTA
	WHERE AR.ID_SEDE = @ID_SEDE
	ORDER BY AR.FECHA_INICIO
)
GO

