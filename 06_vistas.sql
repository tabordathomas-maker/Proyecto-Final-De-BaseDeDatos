IF EXISTS (SELECT * FROM SYS.sysobjects WHERE NAME = 'VW_AGENDA_RESERVAS'
AND xtype = 'V') -- con xtype = 'V', significa una vista
DROP VIEW VW_AGENDA_RESERVAS
GO

CREATE VIEW VW_AGENDA_RESERVAS
AS
SELECT R.ID_RESERVA, R.CODIGO_RESERVA, R.FECHA_INICIO, R.FECHA_FIN,
DATEDIFF(DAY, R.FECHA_INICIO, R.FECHA_FIN) AS DIAS_ALQUILER,  -- COLUMNA CALCULADA: SOLO LECTURA
R.ESTADO AS ESTADO_RESERVA,
C.ID_CLIENTE, C.NOMBRES AS NOMBRE_CLIENTE, C.ESTADO AS ESTADO_CLIENTE,
C.CATEGORIA_LICENCIA AS LICENCIA_CLIENTE, C.VENCIMIENTO_LICENCIA,
R.ID_VEHICULO, V.PLACA, MA.NOMBRE AS MARCA, MO.NOMBRE AS MODELO,
V.CATEGORIA_LICENCIA AS LICENCIA_REQUERIDA,
R.ID_SEDE, S.NOMBRE AS SEDE_RECOGIDA,
P.NOMBRE AS POLIZA, M.NOMBRE AS MODALIDAD

FROM RESERVA R  -- "R" es el alias de RESERVA
INNER JOIN CLIENTE C ON C.ID_CLIENTE = R.ID_CLIENTE  -- Se iguala PK con FK
INNER JOIN VEHICULO V ON V.ID_VEHICULO = R.ID_VEHICULO
INNER JOIN MODELO MO ON MO.ID_MODELO = V.ID_MODELO
INNER JOIN MARCA MA ON MA.ID_MARCA = MO.ID_MARCA
INNER JOIN SEDE S ON S.ID_SEDE = R.ID_SEDE
INNER JOIN POLIZA P ON P.ID_POLIZA = R.ID_POLIZA
INNER JOIN MODALIDAD M ON M.ID_MODALIDAD = R.ID_MODALIDAD

WHERE R.ESTADO IN ('CONFIRMADA', 'MODIFICADA')  -- SOLO LAS QUE FALTA ENTREGAR
GO

-- PRUEBA DE LA VISTA
SELECT * FROM VW_AGENDA_RESERVAS
ORDER BY FECHA_INICIO  -- TOTAL REGISTROS 8

