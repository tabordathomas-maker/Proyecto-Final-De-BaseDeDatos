BEGIN TRY
	BEGIN TRANSACTION

	SELECT 'ANTES' AS MOMENTO, AR.CODIGO_RESERVA, AR.ID_SEDE, AR.SEDE_RECOGIDA, AR.ESTADO_RESERVA
	FROM VW_AGENDA_RESERVAS AR
	WHERE AR.CODIGO_RESERVA = 'RV2611015101'

	UPDATE VW_AGENDA_RESERVAS
	SET ID_SEDE = 1,                    -- COLUMNA DE RESERVA
		ESTADO_RESERVA = 'MODIFICADA'   -- COLUMNA DE RESERVA (ES R.ESTADO)
