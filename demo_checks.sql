(EL CASO DICE QUE EL DESCUENTO VA DEL 5 % AL 10 %)
RESULTADO ESPERADO: RECHAZADO POR CK_CONVENIO_PORCENTAJE_DESCUENTO
*/

BEGIN TRY
	BEGIN TRANSACTION
		INSERT INTO TIPO_EMPRESA (NOMBRE) VALUES ('ASEGURADORA')
