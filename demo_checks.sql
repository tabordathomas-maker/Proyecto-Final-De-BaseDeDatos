		VALUES (SCOPE_IDENTITY(), 'EMPRESA DEMO', 15)
	ROLLBACK TRANSACTION
	PRINT 'DEMO 1: OJO, LA BD NO RECHAZÓ EL DATO'
END TRY

BEGIN CATCH
