PARÁMETROS     : @CALIF_SERVICIO INT, @CALIF_VEHICULO INT (DE 1 A 5)
RETORNO        : VARCHAR(20). LA CLASIFICACIÓN
EJEMPLO        : PRINT DBO.FN_NIVEL_SATISFACCION(5, 2)  -> PROMEDIO 3.5 -> 'BUENA'
