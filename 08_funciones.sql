-- =============================================
-- Author:		<THOMAS>
-- Create date: <10-11-2026>
-- Description:	<FUNCIÓN ESCALAR 2 - NIVEL DE SATISFACCIÓN DE LA ENCUESTA>
-- =============================================
CREATE FUNCTION FN_NIVEL_SATISFACCION
(
@CALIF_SERVICIO INT,
@CALIF_VEHICULO INT
)
RETURNS VARCHAR(20)
AS
BEGIN

	DECLARE @PROMEDIO DECIMAL(3,1)
	DECLARE @MENSAJE VARCHAR(20)

	SET @PROMEDIO = (@CALIF_SERVICIO + @CALIF_VEHICULO) / 2.0  -- "2.0" PARA QUE NO SE PIERDA EL DECIMAL

	IF @PROMEDIO IS NULL
		SET @MENSAJE = 'SIN ENCUESTA'  -- EL CLIENTE NO LLENÓ LA ENCUESTA
	ELSE IF @PROMEDIO >= 4.5
		SET @MENSAJE = 'EXCELENTE'
	ELSE IF @PROMEDIO >= 3.5
		SET @MENSAJE = 'BUENA'
	ELSE IF @PROMEDIO >= 2.5
		SET @MENSAJE = 'REGULAR'
	ELSE
		SET @MENSAJE = 'MALA'

	RETURN @MENSAJE

END
GO

