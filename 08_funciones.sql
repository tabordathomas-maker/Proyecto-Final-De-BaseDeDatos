DESARROLLAR UNA FUNCIÓN ESCALAR QUE CONVIERTA UN VALOR EN PESOS (COP) A LA MONEDA QUE
ELIJA EL CLIENTE: COP, USD O EUR, SEGÚN LA TRM.

REGLA DEL CASO : "EL COSTO DEL SERVICIO SE OFRECE EN TRES MONEDAS DIFERENTES: COP, USD,
                 EUR (DE ACUERDO CON LA TRM VIGENTE PARA CADA MONEDA)".
BENEFICIO      : EL CLIENTE EXTRANJERO VE EL PRECIO EN SU MONEDA. LOS PRECIOS SE GUARDAN
                 SOLO EN COP, Y LA CONVERSIÓN SE HACE EN UN SOLO LUGAR.
PARÁMETROS     : @VALOR_COP DECIMAL(14,2), @MONEDA CHAR(3) ('COP', 'USD' O 'EUR')
RETORNO        : DECIMAL(14,2). EL VALOR EN LA MONEDA PEDIDA (NULL SI LA MONEDA NO EXISTE)
EJEMPLO        : PRINT DBO.FN_CONVERTIR_MONEDA(1026000, 'USD')  -> 1026000 / 4000 = 256.50
OJO            : LA TRM SE ESCRIBE AQUÍ COMO VALOR DE REFERENCIA (USD = 4.000, EUR = 4.600).
                 EN EL SISTEMA REAL SALDRÍA DE UNA TABLA CON LA TRM DE CADA DÍA.
