                 USD Y EUR".
BENEFICIO      : LA PÁGINA WEB LLAMA UNA SOLA FUNCIÓN CON LO QUE ELIGE EL CLIENTE Y LE
                 MUESTRA EL PRECIO DEL DÍA YA CALCULADO Y EN SU MONEDA.
PARÁMETROS     : @GAMA VARCHAR(45)  ('BAJA', 'MEDIA', 'ALTA' O '%' PARA TODAS)
                 @ID_MODALIDAD INT   (1 = POR KILOMETRAJE, 2 = POR DÍA)
                 @MONEDA CHAR(3)     ('COP', 'USD' O 'EUR')
RETORNO        : TABLA. UNA FILA POR VEHÍCULO DISPONIBLE
USA            : FN_CONVERTIR_MONEDA (ESCALAR 3)
TABLAS (7)     : VEHICULO - MODELO - MARCA - MULTIMEDIA_VEHICULO - TIPO_MULTIMEDIA -
                 TARIFA - MODALIDAD
CÓMO SE HALLA LA TARIFA: SE UNE CON LA TARIFA DE LA MISMA GAMA Y MODALIDAD CUYO RANGO
                 (KM_MIN A KM_MAX) CONTIENE EL KILOMETRAJE DEL VEHÍCULO. EL ÚLTIMO RANGO
                 NO TIENE TOPE (KM_MAX NULL).
EJEMPLO        : SELECT * FROM DBO.FN_CATALOGO_PRECIOS('BAJA', 2, 'USD')  -> 8 REGISTROS
*/

-- =============================================
-- Author:		<THOMAS>
-- Create date: <10-11-2026>
-- Description:	<FUNCIÓN DE TABLA 3 - CATÁLOGO DE DISPONIBLES CON PRECIO EN COP, USD O EUR>
-- =============================================
CREATE FUNCTION FN_CATALOGO_PRECIOS
(
@GAMA VARCHAR(45),
@ID_MODALIDAD INT,
@MONEDA CHAR(3)
)
RETURNS TABLE
AS
RETURN
(
	-- NECESITO VEHICULO - MODELO - MARCA - MULTIMEDIA_VEHICULO - TIPO_MULTIMEDIA - TARIFA - MODALIDAD
	SELECT TOP(100) V.PLACA, MA.NOMBRE AS MARCA, MO.NOMBRE AS MODELO, V.GAMA,
	V.CAPACIDAD, V.TRANSMISION, V.COMBUSTIBLE, V.KILOMETRAJE,
	MD.NOMBRE AS MODALIDAD,
	T.VALOR_DIA AS VALOR_DIA_COP,
	@MONEDA AS MONEDA,
	DBO.FN_CONVERTIR_MONEDA(T.VALOR_DIA, @MONEDA) AS VALOR_DIA_MONEDA,  -- ESCALAR 3
	MV.URL AS FOTO_FRONTAL
	FROM VEHICULO V  -- "V" es el alias de VEHICULO
	INNER JOIN MODELO MO ON MO.ID_MODELO = V.ID_MODELO  -- Se iguala PK con FK
	INNER JOIN MARCA MA ON MA.ID_MARCA = MO.ID_MARCA
	INNER JOIN MULTIMEDIA_VEHICULO MV ON V.ID_VEHICULO = MV.ID_VEHICULO
	INNER JOIN TIPO_MULTIMEDIA TM ON TM.ID_TIPO_MULTIMEDIA = MV.ID_TIPO_MULTIMEDIA
	INNER JOIN TARIFA T ON T.GAMA = V.GAMA  -- LA TARIFA DE SU GAMA...
		AND T.ID_MODALIDAD = @ID_MODALIDAD  -- ...EN LA MODALIDAD ELEGIDA...
		AND T.KM_MIN <= V.KILOMETRAJE       -- ...Y EN SU RANGO DE KILOMETRAJE
		AND (T.KM_MAX >= V.KILOMETRAJE OR T.KM_MAX IS NULL)  -- EL ÚLTIMO RANGO NO TIENE TOPE
	INNER JOIN MODALIDAD MD ON MD.ID_MODALIDAD = T.ID_MODALIDAD
	WHERE V.ESTADO = 'DISPONIBLE'      -- SOLO LOS QUE SE PUEDEN RESERVAR
	AND V.ES_RESPALDO = 0              -- EL STOCK DE RESPALDO NO SE PUEDE RESERVAR
	AND TM.NOMBRE = 'FOTO - FRONTAL'   -- UNA SOLA FOTO POR VEHÍCULO (ASÍ NO SE REPITEN FILAS)
	AND V.GAMA LIKE @GAMA              -- CON '%' SALEN TODAS LAS GAMAS
	ORDER BY T.VALOR_DIA, V.PLACA      -- DEL MÁS BARATO AL MÁS CARO
)
GO

SELECT * FROM DBO.FN_CATALOGO_PRECIOS('BAJA', 2, 'USD')  -- TOTAL REGISTROS 8
