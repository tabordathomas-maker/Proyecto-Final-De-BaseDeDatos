EN UN ALQUILER: KILOMETRAJE DEL ACTA DE DEVOLUCIÓN MENOS EL DEL ACTA DE ENTREGA.

REGLA DEL CASO : "EN LA ENTREGA Y EN LA DEVOLUCIÓN SE REGISTRA EL KILOMETRAJE" E
                 "HISTORIAL DEL VEHÍCULO CON EL KILOMETRAJE RECORRIDO".
