-- =============================================
-- Author:		<THOMAS>
-- Create date: <10-11-2026>
-- Description:	<FUNCIÓN ESCALAR 1 - KM RECORRIDOS EN UN ALQUILER>
-- =============================================
CREATE FUNCTION FN_KM_RECORRIDOS
(
@ID_ALQUILER INT
)
RETURNS INT
AS
BEGIN

	DECLARE @KM_ENTREGA INT
	DECLARE @KM_DEVOLUCION INT
	DECLARE @KM_RECORRIDOS INT

	SELECT @KM_ENTREGA = I.KILOMETRAJE
	FROM INSPECCION I  -- "I" es el alias de INSPECCION
	WHERE I.ID_ALQUILER = @ID_ALQUILER
	AND I.ID_TIPO_INSPECCION = 1  -- 1 = ACTA DE ENTREGA

	SELECT @KM_DEVOLUCION = I.KILOMETRAJE
	FROM INSPECCION I
	WHERE I.ID_ALQUILER = @ID_ALQUILER
	AND I.ID_TIPO_INSPECCION = 2  -- 2 = ACTA DE DEVOLUCIÓN

	IF @KM_DEVOLUCION IS NULL
		SET @KM_RECORRIDOS = 0  -- AÚN NO SE HA DEVUELTO: NO HAY KM QUE CONTAR
	ELSE
		SET @KM_RECORRIDOS = @KM_DEVOLUCION - @KM_ENTREGA

	RETURN @KM_RECORRIDOS

END
GO

