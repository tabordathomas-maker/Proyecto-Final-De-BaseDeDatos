REGLA DEL CASO : "GENERAR LISTADO DE VEHÍCULOS MÁS ALQUILADOS POR RANGO DE FECHAS
                 ORGANIZADO POR MARCA Y GAMA".
BENEFICIO      : EL GERENTE SABE QUÉ MARCAS Y GAMAS PIDE MÁS EL CLIENTE Y CUÁNTO DINERO
                 DEJAN, PARA DECIDIR QUÉ CARROS COMPRAR.
PARÁMETROS     : @DESDE DATE, @HASTA DATE (SE CUENTAN LOS ALQUILERES ENTREGADOS EN ESE RANGO,
                 INCLUIDOS LOS DOS DÍAS)
RETORNO        : TABLA. UNA FILA POR MARCA Y GAMA
USA            : FN_CONVERTIR_MONEDA (ESCALAR 3)
TABLAS (6)     : ALQUILER - RESERVA - VEHICULO - MODELO - MARCA - FACTURA
POR QUÉ DATEDIFF: ASÍ SE INCLUYE TODO EL DÍA @HASTA (UN ALQUILER DEL 31-12 A LAS 10 AM
                 SÍ ENTRA). DATEDIFF >= 0 SIGNIFICA "NO ES ANTES DE ESA FECHA".
EJEMPLO        : SELECT * FROM DBO.FN_MAS_ALQUILADOS('20250101', '20251231')  -> 13 REGISTROS
*/

-- =============================================
-- Author:		<THOMAS>
-- Create date: <10-11-2026>
-- Description:	<FUNCIÓN DE TABLA 2 - MÁS ALQUILADOS POR MARCA Y GAMA EN UN RANGO DE FECHAS>
-- =============================================
CREATE FUNCTION FN_MAS_ALQUILADOS
(
@DESDE DATE,
@HASTA DATE
)
RETURNS TABLE
AS
RETURN
(
	-- NECESITO ALQUILER - RESERVA - VEHICULO - MODELO - MARCA - FACTURA
	SELECT TOP(100) MA.NOMBRE AS MARCA, V.GAMA,
	SUM(1) AS VECES_ALQUILADO,  -- CADA FILA ES UN ALQUILER: SE SUMA 1 POR FILA
	SUM(DATEDIFF(DAY, A.FECHA_ENTREGA, A.FECHA_DEVOLUCION)) AS DIAS_ALQUILADO,
	SUM(F.TOTAL) AS TOTAL_FACTURADO_COP,
	AVG(F.TOTAL) AS PROMEDIO_FACTURA_COP,
	DBO.FN_CONVERTIR_MONEDA(SUM(F.TOTAL), 'USD') AS TOTAL_FACTURADO_USD  -- ESCALAR 3
	FROM ALQUILER A  -- "A" es el alias de ALQUILER
	INNER JOIN RESERVA R ON R.ID_RESERVA = A.ID_RESERVA  -- Se iguala PK con FK
	INNER JOIN VEHICULO V ON V.ID_VEHICULO = R.ID_VEHICULO
	INNER JOIN MODELO MO ON MO.ID_MODELO = V.ID_MODELO
	INNER JOIN MARCA MA ON MA.ID_MARCA = MO.ID_MARCA
	INNER JOIN FACTURA F ON A.ID_ALQUILER = F.ID_ALQUILER
	WHERE DATEDIFF(DAY, @DESDE, A.FECHA_ENTREGA) >= 0  -- ENTREGADO DESDE @DESDE...
	AND DATEDIFF(DAY, A.FECHA_ENTREGA, @HASTA) >= 0    -- ...HASTA @HASTA (INCLUIDO)
	GROUP BY MA.NOMBRE, V.GAMA
	ORDER BY VECES_ALQUILADO DESC, TOTAL_FACTURADO_COP DESC
)
GO

