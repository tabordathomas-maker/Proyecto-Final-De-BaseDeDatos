-- =============================================
-- Author:		<THOMAS>
-- Create date: <10-11-2026>
-- Description:	<FUNCIÓN ESCALAR 3 - CONVERTIR COP A USD O EUR CON LA TRM>
-- =============================================
CREATE FUNCTION FN_CONVERTIR_MONEDA
(
@VALOR_COP DECIMAL(14,2),
@MONEDA CHAR(3)
)
RETURNS DECIMAL(14,2)
AS
BEGIN

	DECLARE @TRM_USD DECIMAL(14,2)
	DECLARE @TRM_EUR DECIMAL(14,2)
	DECLARE @RESULTADO DECIMAL(14,2)

	SET @TRM_USD = 4000.00  -- PESOS POR 1 DÓLAR (VALOR DE REFERENCIA)
	SET @TRM_EUR = 4600.00  -- PESOS POR 1 EURO (VALOR DE REFERENCIA)

	IF @MONEDA = 'COP'
		SET @RESULTADO = @VALOR_COP  -- YA ESTÁ EN PESOS
	ELSE IF @MONEDA = 'USD'
		SET @RESULTADO = @VALOR_COP / @TRM_USD
	ELSE IF @MONEDA = 'EUR'
		SET @RESULTADO = @VALOR_COP / @TRM_EUR
	ELSE
		SET @RESULTADO = NULL  -- MONEDA QUE NO MANEJA LA EMPRESA

	RETURN @RESULTADO

END
GO

