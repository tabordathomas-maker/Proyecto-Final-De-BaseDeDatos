BENEFICIO      : EL GERENTE VE LA VIDA DEL CARRO EN UNA SOLA LLAMADA, PARA DECIDIR SI
                 LO MANDA AL TALLER O LO SACA DE LA FLOTA.
PARÁMETROS     : @PLACA VARCHAR(10)
RETORNO        : TABLA. UNA FILA POR ALQUILER DEL VEHÍCULO
USA            : FN_KM_RECORRIDOS (ESCALAR 1) Y FN_NIVEL_SATISFACCION (ESCALAR 2)
TABLAS (7)     : VEHICULO - RESERVA - ALQUILER - CLIENTE - ENCUESTA - INSPECCION - DANIO
POR QUÉ LEFT   : UN ALQUILER PUEDE NO TENER ENCUESTA NI DAÑOS, Y AUN ASÍ DEBE SALIR.
                 LOS DAÑOS SON SOLO LOS DEL ACTA DE DEVOLUCIÓN Y CON VALOR (LOS "PREVIOS"
                 VALEN 0 Y NO SON DEL CLIENTE).
EJEMPLO        : SELECT * FROM DBO.FN_HISTORIAL_VEHICULO('DOD997')  -> 6 REGISTROS
