-- =============================================
-- Author:		<THOMAS>
-- Create date: <10-11-2026>
-- Description:	<FUNCIÓN DE TABLA 1 - HISTORIAL DE UN VEHÍCULO>
-- =============================================
CREATE FUNCTION FN_HISTORIAL_VEHICULO
(
@PLACA VARCHAR(10)
)
RETURNS TABLE
AS
RETURN
(
	-- NECESITO VEHICULO - RESERVA - ALQUILER - CLIENTE - ENCUESTA - INSPECCION - DANIO
	SELECT TOP(100) V.PLACA, R.CODIGO_RESERVA, UPPER(C.NOMBRES) AS NOMBRE_CLIENTE,
	A.FECHA_ENTREGA, A.FECHA_DEVOLUCION,
	DATEDIFF(DAY, A.FECHA_ENTREGA, A.FECHA_DEVOLUCION) AS DIAS_ALQUILADO,
	DBO.FN_KM_RECORRIDOS(A.ID_ALQUILER) AS KM_RECORRIDOS,  -- ESCALAR 1
	E.CALIF_SERVICIO, E.CALIF_VEHICULO,
	DBO.FN_NIVEL_SATISFACCION(E.CALIF_SERVICIO, E.CALIF_VEHICULO) AS SATISFACCION,  -- ESCALAR 2
	SUM(CASE WHEN D.ID_DANO IS NULL THEN 0 ELSE 1 END) AS NUMERO_DANIOS,  -- 1 POR CADA DAÑO, 0 SI NO HAY
	SUM(CASE WHEN D.ID_DANO IS NULL THEN 0 ELSE D.VALOR END) AS VALOR_DANIOS
	FROM VEHICULO V  -- "V" es el alias de VEHICULO
	INNER JOIN RESERVA R ON V.ID_VEHICULO = R.ID_VEHICULO  -- Se iguala PK con FK
	INNER JOIN ALQUILER A ON R.ID_RESERVA = A.ID_RESERVA  -- SOLO RESERVAS QUE SE VOLVIERON ALQUILER
	INNER JOIN CLIENTE C ON C.ID_CLIENTE = R.ID_CLIENTE
	LEFT JOIN ENCUESTA E ON A.ID_ALQUILER = E.ID_ALQUILER
	LEFT JOIN INSPECCION I ON A.ID_ALQUILER = I.ID_ALQUILER
		AND I.ID_TIPO_INSPECCION = 2  -- SOLO EL ACTA DE DEVOLUCIÓN
	LEFT JOIN DANIO D ON I.ID_INSPECCION = D.ID_INSPECCION
		AND D.VALOR > 0  -- SOLO DAÑOS CON VALOR (LOS PREVIOS VALEN 0)
	WHERE V.PLACA = @PLACA  -- EL "WHERE" ES PARA CONTROLAR
	GROUP BY V.PLACA, R.CODIGO_RESERVA, C.NOMBRES, A.ID_ALQUILER, A.FECHA_ENTREGA,
	A.FECHA_DEVOLUCION, E.CALIF_SERVICIO, E.CALIF_VEHICULO
	ORDER BY A.FECHA_ENTREGA  -- CON ORDER BY LA FUNCIÓN NECESITA TOP
)
GO

