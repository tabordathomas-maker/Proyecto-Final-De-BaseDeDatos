/*
FUNCIÓN DE TABLA 2:
DESARROLLAR UNA FUNCIÓN DE TABLA QUE LISTE LOS VEHÍCULOS MÁS ALQUILADOS EN UN RANGO DE
FECHAS, ORGANIZADO POR MARCA Y GAMA, CON LAS VECES QUE SE ALQUILARON, LOS DÍAS
