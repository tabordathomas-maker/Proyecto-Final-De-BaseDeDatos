PARÁMETROS     : @ID_ALQUILER INT
RETORNO        : INT. KM RECORRIDOS (0 SI EL VEHÍCULO AÚN NO SE HA DEVUELTO)
EJEMPLO        : PRINT DBO.FN_KM_RECORRIDOS(1)  -> 34029 - 33799 = 230
